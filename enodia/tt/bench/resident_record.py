@dataclass(frozen=True)
class ResidentInvariant:
    """One executable record relationship in the shared invariant catalog."""

    name: str
    fields: tuple[str, ...]
    description: str
    check: Callable[[Mapping[str, Any], ValidationContext], list[dict[str, Any]]]


@dataclass(frozen=True)
class ValidationContext:
    """Evidence supplied alongside a record to make derived checks possible."""

    timestamps: list[int] | None
    raw_metadata: Mapping[str, Any] | None
    power_trace_path: Path | None
    power_trace_metadata: Mapping[str, Any] | None
    power_trace_bytes: bytes | None
    strict_trace: bool
    builder: bool


def _mismatch(
    invariant: str,
    fields: Iterable[str],
    message: str,
    *,
    soft: bool = False,
) -> dict[str, Any]:
    return {
        "invariant": invariant,
        "fields": list(fields),
        "message": message,
        "soft": soft,
    }


def _is_int(value: Any, *, nonnegative: bool = False, positive: bool = False) -> bool:
    if isinstance(value, bool) or not isinstance(value, int):
        return False
    if nonnegative and value < 0:
        return False
    return not (positive and value <= 0)


def _is_number(value: Any) -> bool:
    if not isinstance(value, (int, float)) or isinstance(value, bool):
        return False
    try:
        return math.isfinite(float(value))
    except OverflowError:
        return False


def _value(record: Mapping[str, Any], path: str, default: Any = _MISSING) -> Any:
    current: Any = record
    for component in path.split("."):
        if not isinstance(current, Mapping) or component not in current:
            return default
        current = current[component]
    return current


def _mapping(record: Mapping[str, Any], path: str) -> Mapping[str, Any] | None:
    value = _value(record, path)
    return value if isinstance(value, Mapping) else None


def _is_modern_record(record: Mapping[str, Any]) -> bool:
    schema = record.get("schema", _MISSING)
    if schema == RESIDENT_RECORD_SCHEMA:
        return True
    # A single-field mutation must not erase the validator's ability to
    # identify a modern record; named historical schemas remain the only skip.
    return schema is _MISSING and any(
        field in record
        for field in ("parameters", "clock", "outlier_analysis", "clock_source_evidence")
    )


def _record_kind(record: Mapping[str, Any]) -> str | None:
    if not _is_modern_record(record):
        return None
    if record.get("status") == RECORD_KIND_REJECTED:
        return RECORD_KIND_REJECTED
    failure = record.get("failure_check")
    failure_code = failure.get("code") if isinstance(failure, Mapping) else _MISSING
    if (
        _is_int(failure_code, nonnegative=True)
        and failure_code != 0
    ) or (
        record.get("status") in {"error", "abnormal_exit", "timeout"}
        and failure_code is _MISSING
    ):
        return RECORD_KIND_ERROR
    sampler = record.get("telemetry_sampler")
    if isinstance(sampler, Mapping) and sampler.get("mode") == "off":
        return RECORD_KIND_SAMPLER_OFF
    return RECORD_KIND_SAMPLED_TIMING


def _path_present(record: Mapping[str, Any], path: str) -> bool:
    return _value(record, path) is not _MISSING


def _check_required_fields(record: Mapping[str, Any], ctx: ValidationContext) -> list[dict[str, Any]]:
    """Enforce the modern shape before any relationship or value checks."""
    del ctx
    kind = _record_kind(record)
    if kind is None:
        return []
    invariant = "record.required_fields"
    mismatches: list[dict[str, Any]] = []
    for path in RESIDENT_RECORD_FIELD_MATRIX[kind]:
        if not _path_present(record, path):
            mismatches.append(
                _mismatch(
                    invariant,
                    (path,),
                    f"{path} is required for {kind} records",
                )
            )
    outlier = record.get("outlier_analysis")
    if isinstance(outlier, Mapping):
        pairs = outlier.get("pairs")
        if isinstance(pairs, list):
            for index, pair in enumerate(pairs):
                if not isinstance(pair, Mapping):
                    continue
                for field in REQUIRED_PAIR_FIELDS:
                    if field not in pair:
                        mismatches.append(
                            _mismatch(
                                invariant,
                                (f"outlier_analysis.pairs[{index}].{field}",),
                                f"outlier_analysis.pairs[{index}].{field} is required for {kind} records",
                            )
                        )
        comparison = outlier.get("sampler_interval_comparison")
        if isinstance(comparison, Mapping):
            gaps = comparison.get("adjacent_gaps")
            if isinstance(gaps, list):
                for index, gap in enumerate(gaps):
                    if not isinstance(gap, Mapping):
                        continue
                    for field in REQUIRED_SAMPLER_GAP_FIELDS:
                        if field not in gap:
                            mismatches.append(
                                _mismatch(
                                    invariant,
                                    (
                                        "outlier_analysis.sampler_interval_comparison."
                                        f"adjacent_gaps[{index}].{field}"
                                    ),
                                    "sampler interval gap field is required for "
                                    f"{kind} records",
                                )
                            )
    return mismatches


def _is_pinned_image(value: Any) -> bool:
    return (
        isinstance(value, str)
        and re.search(r"@sha256:[0-9a-f]{64}$", value) is not None
    )


def _finite_float(value: Any, field: str) -> float:
    """Convert one derived measurement only when the result is finite."""
    try:
        converted = float(value)
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError(f"{field} must be finite") from exc
    if not math.isfinite(converted):
        raise ValueError(f"{field} must be finite")
    return converted


def _finite_ratio(numerator: int, denominator: int, field: str) -> float:
    if denominator == 0:
        raise ValueError(f"{field} denominator must be non-zero")
    try:
        result = numerator / denominator
    except (OverflowError, ZeroDivisionError) as exc:
        raise ValueError(f"{field} must be finite") from exc
    return _finite_float(result, field)


def _pair_order(first: int, second: int) -> str:
    if first < SHORT_THRESHOLD_TICKS and second > LONG_THRESHOLD_TICKS:
        return "short-first"
    if first > LONG_THRESHOLD_TICKS and second < SHORT_THRESHOLD_TICKS:
        return "long-first"
    return "other"


def _is_paired_outlier(first: int, second: int) -> bool:
    return (
        abs(first + second - PAIR_TARGET_TICKS) <= PAIR_TOLERANCE_TICKS
        and _pair_order(first, second) != "other"
    )


def detect_pairs(timestamps: Iterable[int]) -> list[dict[str, Any]]:
    """Detect adjacent short/long pairs using the shared Issue #104 rule."""
    values = list(timestamps)
    if any(not _is_int(value, nonnegative=True) for value in values):
        raise ValueError("timestamps must contain unsigned integer values")
    if any(current <= previous for previous, current in itertools.pairwise(values)):
        raise ValueError("timestamps must be strictly increasing")
    intervals = [current - previous for previous, current in itertools.pairwise(values)]
    pairs: list[dict[str, Any]] = []
    for interval_index, (first, second) in enumerate(itertools.pairwise(intervals)):
        if not _is_paired_outlier(first, second):
            continue
        first_endpoint = interval_index + 1
        first_elapsed = values[first_endpoint] - values[0]
        pair_sum = first + second
        pairs.append(
            {
                "interval_end_frame_indices": [first_endpoint, first_endpoint + 1],
                "short_ticks": min(first, second),
                "long_ticks": max(first, second),
                "first_interval_ticks": first,
                "second_interval_ticks": second,
                "pair_sum_ticks": pair_sum,
                "sum_delta_ticks": pair_sum - PAIR_TARGET_TICKS,
                "order": _pair_order(first, second),
                "first_interval_end_elapsed_ticks": first_elapsed,
                "first_interval_end_elapsed_ticks_mod_period": first_elapsed % CLOCK_MODULUS_TICKS,
            }
        )
    return pairs


# Compatibility spelling used by the board-free analyzer and its existing
# callers.  The implementation remains in this module, not in the analyzer.
_detect_pairs = detect_pairs


def _count_orders(pairs: Iterable[Mapping[str, Any]]) -> dict[str, int]:
    counts = Counter({order: 0 for order in PAIR_ORDERS})
    for pair in pairs:
        order = pair.get("order")
        if order not in counts:
            counts["other"] += 1
        else:
            counts[str(order)] += 1
    return {order: counts[order] for order in PAIR_ORDERS}


def _duplicate_values(values: Iterable[int]) -> list[int]:
    return sorted(value for value, count in Counter(values).items() if count > 1)


def _counter_difference(left: Iterable[int], right: Iterable[int]) -> list[int]:
    return sorted((Counter(left) - Counter(right)).elements())


def _ordered_mismatches(left: list[Any], right: list[Any]) -> list[int]:
    return [
        index
        for index in range(min(len(left), len(right)))
        if left[index] != right[index]
    ]


def _record_pair_starts(record: Mapping[str, Any]) -> list[int]:
    outlier = record.get("outlier_analysis")
    if not isinstance(outlier, Mapping):
        return []
    starts = outlier.get("frame_start_indices", _MISSING)
    pair_count = outlier.get("pair_count")
    pair_sums = outlier.get("pair_sums")
    if starts is _MISSING:
        if type(pair_count) is int and pair_count == 0 and isinstance(pair_sums, list) and not pair_sums:
            return []
        return []
    return list(starts) if isinstance(starts, list) else []


def _record_pairs(record: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    outlier = record.get("outlier_analysis")
    if not isinstance(outlier, Mapping):
        return []
    pairs = outlier.get("pairs", [])
    return list(pairs) if isinstance(pairs, list) else []


def record_correspondence(
    detected_pairs: list[Mapping[str, Any]], record: Mapping[str, Any]
) -> dict[str, Any]:
    """Compare recorded and raw-derived pairs by length, multiset, and order."""
    detected_endpoints = [pair.get("interval_end_frame_indices") for pair in detected_pairs]
    record_starts = _record_pair_starts(record)
    record_pairs = _record_pairs(record)
    record_endpoints = [
        pair.get("interval_end_frame_indices") for pair in record_pairs if isinstance(pair, Mapping)
    ]
    detected_starts = [
        endpoints[0]
        for endpoints in detected_endpoints
        if isinstance(endpoints, list) and endpoints
    ]

    missing = _counter_difference(record_starts, detected_starts)
    unexpected = _counter_difference(detected_starts, record_starts)
    record_duplicate_starts = _duplicate_values(record_starts)
    raw_duplicate_starts = _duplicate_values(detected_starts)

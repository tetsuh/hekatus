def _check_raw_timestamps(record: Mapping[str, Any], ctx: ValidationContext) -> list[dict[str, Any]]:
    invariant = "raw_timestamps"
    fields = ("raw_timestamps.count", "raw_timestamps.sha256")
    raw = _mapping(record, "raw_timestamps")
    if raw is None:
        return [_mismatch(invariant, fields, "raw_timestamps must be an object")]
    mismatches: list[dict[str, Any]] = []
    count = raw.get("count")
    digest = raw.get("sha256")
    if not _is_int(count, nonnegative=True):
        mismatches.append(_mismatch(invariant, ("raw_timestamps.count",), "raw_timestamps.count must be a non-negative integer"))
    if not isinstance(digest, str) or len(digest) != 64 or any(char not in "0123456789abcdefABCDEF" for char in digest):
        mismatches.append(_mismatch(invariant, ("raw_timestamps.sha256",), "raw_timestamps.sha256 must be a 64-character hexadecimal digest"))
    if ctx.timestamps is not None:
        if any(not _is_int(value, nonnegative=True) for value in ctx.timestamps):
            mismatches.append(_mismatch(invariant, ("timestamps",), "supplied timestamps must be unsigned integers"))
        if any(current <= previous for previous, current in itertools.pairwise(ctx.timestamps)):
            mismatches.append(_mismatch(invariant, ("timestamps",), "supplied timestamps must be strictly increasing"))
        if _is_int(count, nonnegative=True) and count != len(ctx.timestamps):
            mismatches.append(_mismatch(invariant, ("raw_timestamps.count", "timestamps"), "raw_timestamps.count does not equal timestamp rows"))
    if ctx.raw_metadata is not None:
        actual_count = ctx.raw_metadata.get("count")
        actual_hash = ctx.raw_metadata.get("sha256")
        if _is_int(count, nonnegative=True) and count != actual_count:
            mismatches.append(_mismatch(invariant, ("raw_timestamps.count", "raw_metadata.count"), "raw_timestamps.count does not equal actual raw bytes"))
        if isinstance(digest, str) and digest != actual_hash:
            mismatches.append(_mismatch(invariant, ("raw_timestamps.sha256", "raw_metadata.sha256"), "raw_timestamps.sha256 does not match actual raw bytes"))
    return mismatches


def _intervals(timestamps: list[int]) -> list[int]:
    return [current - previous for previous, current in itertools.pairwise(timestamps)]


def _required_samples(percentile: float) -> int:
    threshold = Fraction(20, 1) / (1 - Fraction(str(percentile)))
    return (threshold.numerator + threshold.denominator - 1) // threshold.denominator


def _linear_percentile(values: list[int], percentile: float) -> float:
    position = (len(values) - 1) * percentile
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return float(values[lower])
    fraction = position - lower
    return values[lower] + fraction * (values[upper] - values[lower])


def _check_histogram(record: Mapping[str, Any], ctx: ValidationContext) -> list[dict[str, Any]]:
    invariant = "histogram"
    histogram = _mapping(record, "histogram")
    if histogram is None:
        return [_mismatch(invariant, ("histogram",), "histogram must be an object")]
    mismatches: list[dict[str, Any]] = []
    raw = _mapping(record, "raw_timestamps")
    raw_count = raw.get("count") if raw else None
    declared_n = histogram.get("N")
    if not _is_int(declared_n, nonnegative=True):
        mismatches.append(_mismatch(invariant, ("histogram.N",), "histogram.N must be a non-negative integer"))
    expected_n = None
    if _is_int(raw_count, nonnegative=True):
        expected_n = max(0, raw_count - 1)
    if ctx.timestamps is not None:
        expected_n = max(0, len(ctx.timestamps) - 1)
    if expected_n is not None and _is_int(declared_n, nonnegative=True) and declared_n != expected_n:
        mismatches.append(_mismatch(invariant, ("histogram.N", "raw_timestamps.count"), "histogram N must equal interval count (raw timestamp count minus one)"))
    nested = histogram.get("histogram")
    if not isinstance(nested, Mapping):
        mismatches.append(_mismatch(invariant, ("histogram.histogram",), "histogram.histogram must be an object"))
        return mismatches
    bins = nested.get("bins")
    if not isinstance(bins, list):
        mismatches.append(_mismatch(invariant, ("histogram.histogram.bins",), "histogram bins must be a list"))
        return mismatches
    bin_sum = 0
    width = nested.get("bin_width_ticks")
    if not _is_int(width, positive=True):
        mismatches.append(_mismatch(invariant, ("histogram.histogram.bin_width_ticks",), "histogram bin width must be a positive integer"))
    for index, item in enumerate(bins):
        if not isinstance(item, Mapping):
            mismatches.append(_mismatch(invariant, (f"histogram.histogram.bins[{index}]",), "histogram bin must be an object"))
            continue
        count = item.get("count")
        if not _is_int(count, nonnegative=True):
            mismatches.append(_mismatch(invariant, (f"histogram.histogram.bins[{index}].count",), "histogram bin count must be a non-negative integer"))
        else:
            bin_sum += count
        start = item.get("start_ticks")
        end = item.get("end_ticks")
        if not _is_int(start, nonnegative=True) or not _is_int(end, nonnegative=True):
            mismatches.append(_mismatch(invariant, (f"histogram.histogram.bins[{index}]",), "histogram bin endpoints must be non-negative integers"))
        elif _is_int(width, positive=True) and end != start + width:
            mismatches.append(_mismatch(invariant, (f"histogram.histogram.bins[{index}]", "histogram.histogram.bin_width_ticks"), "histogram bin end must equal start plus bin width"))
    if _is_int(declared_n, nonnegative=True) and bin_sum != declared_n:
        mismatches.append(_mismatch(invariant, ("histogram.N", "histogram.histogram.bins"), "histogram bins do not sum to histogram N"))

    if ctx.timestamps is not None and all(_is_int(value, nonnegative=True) for value in ctx.timestamps):
        actual = _intervals(ctx.timestamps)
        ordered = sorted(actual)
        if histogram.get("min_ticks") != (ordered[0] if ordered else None):
            mismatches.append(_mismatch(invariant, ("histogram.min_ticks", "timestamps"), "histogram min_ticks does not match timestamp intervals"))
        if histogram.get("max_ticks") != (ordered[-1] if ordered else None):
            mismatches.append(_mismatch(invariant, ("histogram.max_ticks", "timestamps"), "histogram max_ticks does not match timestamp intervals"))
        if _is_int(width, positive=True):
            expected_bins: dict[int, int] = {}
            for value in ordered:
                start = (value // width) * width
                expected_bins[start] = expected_bins.get(start, 0) + 1
            actual_bins = {
                item.get("start_ticks"): item.get("count")
                for item in bins
                if isinstance(item, Mapping)
            }
            if actual_bins != expected_bins:
                mismatches.append(_mismatch(invariant, ("histogram.histogram.bins", "timestamps"), "histogram bins do not match timestamp intervals"))
        percentiles = histogram.get("percentiles")
        if isinstance(percentiles, Mapping):
            for name, percentile in (("p50", 0.50), ("p99", 0.99), ("p99_9", 0.999), ("p99_99", 0.9999)):
                entry = percentiles.get(name)
                if not isinstance(entry, Mapping):
                    mismatches.append(_mismatch(invariant, (f"histogram.percentiles.{name}",), "histogram percentile entry is missing"))
                    continue
                threshold = _required_samples(percentile)
                expected_status = "ok" if len(ordered) >= threshold else "insufficient"
                if entry.get("status") != expected_status or entry.get("minimum_samples") != threshold:
                    mismatches.append(_mismatch(invariant, (f"histogram.percentiles.{name}", "histogram.N"), "histogram percentile status or minimum_samples is inconsistent with N"))
                if expected_status == "ok" and entry.get("value_ticks") != _linear_percentile(ordered, percentile):
                    mismatches.append(_mismatch(invariant, (f"histogram.percentiles.{name}", "timestamps"), "histogram percentile value does not match timestamp intervals"))
    return mismatches


def validate_pair_analysis(
    outlier_analysis: Mapping[str, Any],
    *,
    timestamps: Iterable[int] | None = None,
    aiclk_mhz: int | None = None,
    sampler_mode: str | None = None,
    sampler_interval_seconds: float | None = None,
    strict_fields: bool = False,
) -> list[dict[str, Any]]:
    """Return pair mismatches, requiring every modern field when requested."""
    invariant = "outlier_analysis"
    if not isinstance(outlier_analysis, Mapping):
        return [_mismatch(invariant, ("outlier_analysis",), "outlier_analysis must be an object")]
    mismatches: list[dict[str, Any]] = []
    timestamp_values = list(timestamps) if timestamps is not None else None
    pair_count = outlier_analysis.get("pair_count")
    if not _is_int(pair_count, nonnegative=True):
        return [_mismatch(invariant, ("outlier_analysis.pair_count",), "outlier_analysis.pair_count must be a non-negative integer")]
    if strict_fields:
        numeric_fields = (
            "pair_sum_min_ticks",
            "pair_sum_max_ticks",
            "pair_sum_mean_ticks",
            "sum_delta_min_ticks",
            "sum_delta_max_ticks",
            "run_elapsed_seconds",
        )
        for field in numeric_fields:
            value = outlier_analysis.get(field)
            if value is not None and not _is_number(value):
                mismatches.append(
                    _mismatch(
                        invariant,
                        (f"outlier_analysis.{field}",),
                        f"outlier_analysis.{field} must be finite",
                    )
                )
        for field in ("event_elapsed_seconds", "pair_start_elapsed_seconds"):
            values = outlier_analysis.get(field)
            if isinstance(values, list) and any(not _is_number(value) for value in values):
                mismatches.append(
                    _mismatch(
                        invariant,
                        (f"outlier_analysis.{field}",),
                        f"outlier_analysis.{field} must contain finite values",
                    )
                )
        comparison = outlier_analysis.get("sampler_interval_comparison")
        if isinstance(comparison, Mapping):
            for field in ("interval_seconds", "sampler_interval_seconds"):
                value = comparison.get(field)
                if value is not None and not _is_number(value):
                    mismatches.append(
                        _mismatch(
                            invariant,
                            (f"outlier_analysis.sampler_interval_comparison.{field}",),
                            f"sampler interval {field} must be finite",
                        )
                    )
            gaps = comparison.get("adjacent_gaps")
            if isinstance(gaps, list):
                for index, gap in enumerate(gaps):
                    if not isinstance(gap, Mapping):
                        continue
                    for field in (
                        "gap_elapsed_seconds",
                        "residual_to_nearest_sampler_multiple_seconds",
                        "sampler_intervals",
                    ):
                        if not _is_number(gap.get(field)):
                            mismatches.append(
                                _mismatch(
                                    invariant,
                                    (f"outlier_analysis.sampler_interval_comparison.adjacent_gaps[{index}].{field}",),
                                    f"sampler interval gap {field} must be finite",
                                )
                            )
    target = outlier_analysis.get("pair_sum_target_ticks", _MISSING)
    if (strict_fields or target is not _MISSING) and target != PAIR_TARGET_TICKS:
        mismatches.append(_mismatch(invariant, ("outlier_analysis.pair_sum_target_ticks",), "pair_sum_target_ticks does not equal the shared pair target"))
    starts_value = outlier_analysis.get("frame_start_indices", _MISSING)
    if (
        starts_value is _MISSING
        and not strict_fields
        and pair_count == 0
        and outlier_analysis.get("pair_sums") == []
    ):
        starts: list[Any] = []
    elif isinstance(starts_value, list):
        starts = starts_value
    else:
        starts = []
        mismatches.append(_mismatch(invariant, ("outlier_analysis.frame_start_indices",), "outlier_analysis.frame_start_indices must be a list"))
    pairs_value = outlier_analysis.get("pairs", [])
    pairs = pairs_value if isinstance(pairs_value, list) else []
    if not isinstance(pairs_value, list):
        mismatches.append(_mismatch(invariant, ("outlier_analysis.pairs",), "outlier_analysis.pairs must be a list"))
    if len(starts) != pair_count:
        mismatches.append(_mismatch(invariant, ("outlier_analysis.pair_count", "outlier_analysis.frame_start_indices"), "outlier_analysis pair_count must equal frame_start_indices length"))
    if any(not _is_int(value, positive=True) for value in starts):
        mismatches.append(_mismatch(invariant, ("outlier_analysis.frame_start_indices",), "outlier_analysis.frame_start_indices must be positive integers"))
    if len(pairs) != pair_count:
        mismatches.append(_mismatch(invariant, ("outlier_analysis.pair_count", "outlier_analysis.pairs"), "outlier_analysis pair_count must equal pairs length"))
    pair_sums_value = outlier_analysis.get("pair_sums", _MISSING)
    pair_sums: list[Any] | None
    if pair_sums_value is _MISSING:
        pair_sums = None
        if strict_fields:
            mismatches.append(
                _mismatch(
                    invariant,
                    ("outlier_analysis.pair_sums",),
                    "outlier_analysis.pair_sums is required",
                )
            )
    elif isinstance(pair_sums_value, list):
        pair_sums = pair_sums_value
        if len(pair_sums) != pair_count:
            mismatches.append(_mismatch(invariant, ("outlier_analysis.pair_count", "outlier_analysis.pair_sums"), "outlier_analysis pair_count must equal pair_sums length"))
    else:
        pair_sums = None
        mismatches.append(_mismatch(invariant, ("outlier_analysis.pair_sums",), "outlier_analysis.pair_sums must be a list"))
    if _duplicate_values(value for value in starts if _is_int(value)):
        mismatches.append(_mismatch(invariant, ("outlier_analysis.frame_start_indices",), "duplicate frame_start_indices are not allowed"))

    for index, pair in enumerate(pairs):
        if not isinstance(pair, Mapping):
            mismatches.append(_mismatch(invariant, (f"outlier_analysis.pairs[{index}]",), "outlier_analysis.pairs must contain objects"))
            continue
        endpoints = pair.get("interval_end_frame_indices")
        if not isinstance(endpoints, list) or len(endpoints) != 2 or any(not _is_int(value, nonnegative=True) for value in endpoints):
            mismatches.append(_mismatch(invariant, (f"outlier_analysis.pairs[{index}].interval_end_frame_indices",), "pair endpoints must contain two non-negative integers"))
            continue
        if index < len(starts) and endpoints != [starts[index], starts[index] + 1]:
            mismatches.append(_mismatch(invariant, (f"outlier_analysis.pairs[{index}]", "outlier_analysis.frame_start_indices"), "outlier_analysis pair endpoints must match frame starts"))
        if (
            pair_sums is not None
            and index < len(pair_sums)
            and pair.get("pair_sum_ticks") != pair_sums[index]
        ):
            mismatches.append(_mismatch(invariant, (f"outlier_analysis.pairs[{index}].pair_sum_ticks", "outlier_analysis.pair_sums"), "outlier_analysis pair sums must match pair objects"))

    expected_positions = [endpoint for pair in pairs if isinstance(pair, Mapping) for endpoint in pair.get("interval_end_frame_indices", [])]
    if (strict_fields or "event_frame_positions" in outlier_analysis) and outlier_analysis.get("event_frame_positions") != expected_positions:
        mismatches.append(_mismatch(invariant, ("outlier_analysis.event_frame_positions", "outlier_analysis.pairs"), "outlier_analysis event frame positions do not match pair endpoints"))
    for field in ("event_elapsed_seconds", "event_elapsed_ticks", "event_elapsed_ticks_mod_period"):
        if strict_fields or field in outlier_analysis:
            values = outlier_analysis.get(field)
            if not isinstance(values, list) or len(values) != pair_count * 2:
                mismatches.append(_mismatch(invariant, (f"outlier_analysis.{field}", "outlier_analysis.pair_count"), f"{field} length does not equal pair endpoint count"))
    starts_int = [value for value in starts if _is_int(value)]
    expected_gaps = [right - left for left, right in itertools.pairwise(starts_int)]
    if (strict_fields or "frame_gaps" in outlier_analysis) and outlier_analysis.get("frame_gaps") != expected_gaps:
        mismatches.append(_mismatch(invariant, ("outlier_analysis.frame_gaps", "outlier_analysis.frame_start_indices"), "outlier_analysis frame gaps do not match frame starts"))
    if strict_fields or "gap_counts" in outlier_analysis:
        expected_counts = Counter(expected_gaps)
        declared = outlier_analysis.get("gap_counts")
        if not isinstance(declared, Mapping) or {str(key): value for key, value in expected_counts.items()} != dict(declared):
            mismatches.append(_mismatch(invariant, ("outlier_analysis.gap_counts", "outlier_analysis.frame_gaps"), "outlier_analysis gap_counts do not match frame gaps"))
    if strict_fields or "gap_histogram" in outlier_analysis:
        expected_histogram = [{"gap_frames": gap, "count": Counter(expected_gaps)[gap]} for gap in sorted(set(expected_gaps))]
        if outlier_analysis.get("gap_histogram") != expected_histogram:
            mismatches.append(_mismatch(invariant, ("outlier_analysis.gap_histogram", "outlier_analysis.frame_gaps"), "outlier_analysis gap histogram does not match frame gaps"))
    if (strict_fields or "gcd_frame_gap" in outlier_analysis) and outlier_analysis.get("gcd_frame_gap") != _gcd(expected_gaps):
        mismatches.append(_mismatch(invariant, ("outlier_analysis.gcd_frame_gap", "outlier_analysis.frame_gaps"), "outlier_analysis gcd_frame_gap does not match frame gaps"))

    if timestamp_values is not None:
        values = timestamp_values
        try:
            detected = detect_pairs(values)
        except ValueError as exc:
            mismatches.append(_mismatch(invariant, ("timestamps",), f"pair correspondence cannot be computed: {exc}"))
        else:
            correspondence = record_correspondence(detected, {"outlier_analysis": outlier_analysis})
            if not correspondence["exact_frame_start_match"]:
                mismatches.append(_mismatch(invariant, ("outlier_analysis.frame_start_indices", "timestamps"), "derived pair starts do not match by length, multiset, and order"))
            if not correspondence["record_pair_list_length_match"]:
                mismatches.append(_mismatch(invariant, ("outlier_analysis.pairs", "timestamps"), "derived pair list length does not match record"))
            if correspondence["pair_endpoint_mismatches"]:
                mismatches.append(_mismatch(invariant, ("outlier_analysis.pairs", "timestamps"), "derived pair endpoints do not match record"))
            if correspondence["pair_order_mismatches"]:
                mismatches.append(_mismatch(invariant, ("outlier_analysis.pairs", "timestamps"), "derived pair orders do not match record"))
            if correspondence["pair_value_mismatches"]:
                mismatches.append(_mismatch(invariant, ("outlier_analysis.pairs", "timestamps"), "derived pair values do not match record"))
            if correspondence["pair_sum_mismatches"]:
                mismatches.append(_mismatch(invariant, ("outlier_analysis.pairs", "timestamps"), "derived pair sums do not match record"))
            actual_aiclk = aiclk_mhz if _is_int(aiclk_mhz, positive=True) else DEFAULT_AICLK_MHZ
            expected_pairs = build_outlier_analysis(values, aiclk_mhz=actual_aiclk).get("pairs", [])
            expected_interval_count = max(0, len(values) - 1)
            if (strict_fields or "interval_count" in outlier_analysis) and outlier_analysis.get("interval_count") != expected_interval_count:
                mismatches.append(_mismatch(invariant, ("outlier_analysis.interval_count", "timestamps"), "outlier_analysis interval_count does not match timestamps"))
            for index, pair in enumerate(pairs):
                if index >= len(expected_pairs) or not isinstance(pair, Mapping):
                    continue
                expected = expected_pairs[index]
                for field in (
                    "first_interval_ticks",
                    "second_interval_ticks",
                    "short_ticks",
                    "long_ticks",
                    "pair_sum_ticks",
                    "sum_delta_ticks",
                    "order",
                    "first_interval_end_elapsed_ticks",
                    "first_interval_end_elapsed_ticks_mod_period",
                    "first_interval_end_elapsed_seconds",
                ):
                    if (strict_fields or field in pair) and pair.get(field) != expected.get(field):
                        mismatches.append(_mismatch(invariant, (f"outlier_analysis.pairs[{index}].{field}", "timestamps"), f"pair {index} {field} does not match timestamps"))
            expected_pair_sums = [pair["pair_sum_ticks"] for pair in expected_pairs]
            if (strict_fields or pair_sums is not None) and pair_sums != expected_pair_sums:
                mismatches.append(_mismatch(invariant, ("outlier_analysis.pair_sums", "timestamps"), "outlier_analysis pair_sums do not match timestamps"))
            expected_endpoints = [endpoint for pair in expected_pairs for endpoint in pair["interval_end_frame_indices"]]
            expected_elapsed_ticks = [values[index] - values[0] for index in expected_endpoints]
            expected_elapsed_mod = [elapsed % CLOCK_MODULUS_TICKS for elapsed in expected_elapsed_ticks]
            actual_seconds_aiclk = aiclk_mhz if _is_int(aiclk_mhz, positive=True) else DEFAULT_AICLK_MHZ
            expected_elapsed_seconds = [
                _finite_ratio(
                    elapsed,
                    actual_seconds_aiclk * 1_000_000,
                    "expected event elapsed seconds",
                )
                for elapsed in expected_elapsed_ticks
            ]
            for field, expected in (
                ("event_frame_positions", expected_endpoints),
                ("event_elapsed_ticks", expected_elapsed_ticks),
                ("event_elapsed_ticks_mod_period", expected_elapsed_mod),
                ("event_elapsed_seconds", expected_elapsed_seconds),
                ("pair_start_elapsed_seconds", [
                    _finite_ratio(
                        values[index] - values[0],
                        actual_seconds_aiclk * 1_000_000,
                        "expected pair start elapsed seconds",
                    )
                    for index in [pair["interval_end_frame_indices"][0] for pair in expected_pairs]
                ]),
            ):
                if (strict_fields or field in outlier_analysis) and outlier_analysis.get(field) != expected:
                    mismatches.append(_mismatch(invariant, (f"outlier_analysis.{field}", "timestamps"), f"outlier_analysis {field} does not match timestamps"))
            expected_sums = [pair["pair_sum_ticks"] for pair in expected_pairs]
            for field, expected in (
                ("pair_sum_min_ticks", min(expected_sums) if expected_sums else None),
                ("pair_sum_max_ticks", max(expected_sums) if expected_sums else None),
                (
                    "pair_sum_mean_ticks",
                    _finite_ratio(
                        sum(expected_sums), len(expected_sums), "expected pair sum mean ticks"
                    )
                    if expected_sums
                    else None,
                ),
                ("sum_delta_min_ticks", min((value - PAIR_TARGET_TICKS) for value in expected_sums) if expected_sums else None),
                ("sum_delta_max_ticks", max((value - PAIR_TARGET_TICKS) for value in expected_sums) if expected_sums else None),
                ("aiclk_mhz_for_elapsed_seconds", actual_seconds_aiclk),
                ("run_elapsed_ticks", values[-1] - values[0] if values else 0),
                (
                    "run_elapsed_seconds",
                    _finite_ratio(
                        values[-1] - values[0],
                        actual_seconds_aiclk * 1_000_000,
                        "expected run elapsed seconds",
                    )
                    if values
                    else 0.0,
                ),
            ):
                if (strict_fields or field in outlier_analysis) and outlier_analysis.get(field) != expected:
                    mismatches.append(_mismatch(invariant, (f"outlier_analysis.{field}", "timestamps"), f"outlier_analysis {field} does not match timestamps"))
    # Pair sums and order metadata are derivable even without raw timestamps.
    object_sums = [
        pair.get("pair_sum_ticks")
        for pair in pairs
        if isinstance(pair, Mapping) and _is_int(pair.get("pair_sum_ticks"))
    ]
    expected_pair_sum_min = min(object_sums) if object_sums else None
    expected_pair_sum_max = max(object_sums) if object_sums else None
    expected_pair_sum_mean = (
        _finite_ratio(sum(object_sums), len(object_sums), "pair sum mean ticks")
        if object_sums
        else None
    )
    for field, expected_value in (
        ("pair_sum_min_ticks", expected_pair_sum_min),
        ("pair_sum_max_ticks", expected_pair_sum_max),
        ("pair_sum_mean_ticks", expected_pair_sum_mean),
    ):
        if (strict_fields or field in outlier_analysis) and outlier_analysis.get(field) != expected_value:
            mismatches.append(
                _mismatch(
                    invariant,
                    (f"outlier_analysis.{field}", "outlier_analysis.pairs"),
                    f"{field} does not match pair objects",
                )
            )
    object_deltas = [value - PAIR_TARGET_TICKS for value in object_sums]
    for field, expected_value in (
        ("sum_delta_min_ticks", min(object_deltas) if object_deltas else None),
        ("sum_delta_max_ticks", max(object_deltas) if object_deltas else None),
    ):
        if (strict_fields or field in outlier_analysis) and outlier_analysis.get(field) != expected_value:
            mismatches.append(
                _mismatch(
                    invariant,
                    (f"outlier_analysis.{field}", "outlier_analysis.pairs"),
                    f"{field} does not match pair objects",
                )
            )
    expected_order_counts = _count_orders(
        pair for pair in pairs if isinstance(pair, Mapping)
    )
    if (strict_fields or "pair_order_counts" in outlier_analysis) and outlier_analysis.get(
        "pair_order_counts"
    ) != expected_order_counts:
        mismatches.append(
            _mismatch(
                invariant,
                ("outlier_analysis.pair_order_counts", "outlier_analysis.pairs"),
                "pair_order_counts does not match pair objects",
            )
        )

    if timestamp_values is not None and sampler_mode in {"off", "default", "explicit"}:
        actual_timestamps = timestamp_values
        expected = build_outlier_analysis(
            actual_timestamps,
            aiclk_mhz=(aiclk_mhz if _is_int(aiclk_mhz, positive=True) else DEFAULT_AICLK_MHZ),
            sampler_mode=sampler_mode,
            sampler_interval_seconds=sampler_interval_seconds,
        )["sampler_interval_comparison"]
        actual = outlier_analysis.get("sampler_interval_comparison")
        if isinstance(actual, Mapping):
            for field, expected_value in expected.items():
                if (strict_fields or field in actual) and actual.get(field) != expected_value:
                    mismatches.append(
                        _mismatch(
                            invariant,
                            (f"outlier_analysis.sampler_interval_comparison.{field}", "timestamps"),
                            f"sampler interval comparison {field} does not match timestamps",
                        )
                    )
        elif sampler_mode != "off":
            mismatches.append(
                _mismatch(
                    invariant,
                    ("outlier_analysis.sampler_interval_comparison",),
                    "sampled outlier analysis must include sampler interval comparison",
                )
            )

    return mismatches


def _check_clock_source_evidence(
    record: Mapping[str, Any], ctx: ValidationContext
) -> list[dict[str, Any]]:
    """Check evidence against the immutable image-digest audit table."""
    del ctx
    if not _is_modern_record(record):
        return []
    invariant = "clock_source_evidence"
    environment = _mapping(record, "environment")
    evidence = _mapping(record, "clock_source_evidence")
    if environment is None or evidence is None:
        return []
    image = environment.get("image")
    mismatches: list[dict[str, Any]] = []
    kind = _record_kind(record)
    if kind != RECORD_KIND_REJECTED and not _is_pinned_image(image):
        mismatches.append(
            _mismatch(
                invariant,
                ("environment.image", "environment.image_pinned"),
                "environment image must be digest-pinned",
            )
        )
    if evidence.get("image") != image:
        mismatches.append(
            _mismatch(
                invariant,
                ("clock_source_evidence.image", "environment.image"),
                "clock-source evidence image must equal environment.image",
            )
        )
    audited = clock_source_audit_for_image(image)
    if audited is not None:
        if evidence.get("audit_status") != "audited":
            mismatches.append(
                _mismatch(
                    invariant,
                    ("clock_source_evidence.audit_status",),
                    "audited image requires audited clock-source evidence",
                )
            )
        for field, expected in audited.items():
            if evidence.get(field) != expected:
                mismatches.append(
                    _mismatch(
                        invariant,
                        (f"clock_source_evidence.{field}", "environment.image"),
                        f"clock-source evidence {field} does not match the immutable audit table",
                    )
                )
    elif evidence.get("audit_status") != "unaudited":
        mismatches.append(
            _mismatch(
                invariant,
                ("clock_source_evidence.audit_status", "environment.image"),
                "an image without an audit entry must be marked unaudited",
            )
        )
    return mismatches


def _check_pairs(record: Mapping[str, Any], ctx: ValidationContext) -> list[dict[str, Any]]:
    outlier = record.get("outlier_analysis")
    if not isinstance(outlier, Mapping):
        return [_mismatch("outlier_analysis", ("outlier_analysis",), "record is missing outlier_analysis")]
    mismatches: list[dict[str, Any]] = []
    schema = record.get("schema")
    # Compatibility branch: the original ADR-0005 Issue #104 records predate
    # the modern pair-detail fields.  This skips only structural requirements;
    # the independent timing-evidence invariant below still runs.
    legacy = isinstance(schema, str) and schema.startswith("adr-0005-issue-104-")
    if not legacy:
        required = (
            "pair_sum_target_ticks",
            "pair_sums",
            "frame_start_indices",
            "pairs",
            "event_frame_positions",
            "event_elapsed_seconds",
            "event_elapsed_ticks",
            "event_elapsed_ticks_mod_period",
            "frame_gaps",
            "gap_counts",
            "gap_histogram",
            "gcd_frame_gap",
            "interval_count",
            "pair_order_counts",
            "sampler_interval_comparison",
        )
        for field in required:
            if field not in outlier:
                mismatches.append(_mismatch("outlier_analysis", (f"outlier_analysis.{field}",), f"outlier_analysis.{field} is required by the resident schema"))
    if not legacy and isinstance(outlier.get("pairs"), list):
        pair_fields = (
            "interval_end_frame_indices",
            "first_interval_ticks",
            "second_interval_ticks",
            "short_ticks",
            "long_ticks",
            "pair_sum_ticks",
            "sum_delta_ticks",
            "order",
            "first_interval_end_elapsed_ticks",
            "first_interval_end_elapsed_ticks_mod_period",
            "first_interval_end_elapsed_seconds",
        )
        for index, pair in enumerate(outlier["pairs"]):
            if isinstance(pair, Mapping):
                for field in pair_fields:
                    if field not in pair:
                        mismatches.append(_mismatch("outlier_analysis", (f"outlier_analysis.pairs[{index}].{field}",), f"pair {index} {field} is required by the resident schema"))
    clock = _mapping(record, "clock")
    aiclk = clock.get("aiclk_mhz") if clock else None
    sampler = _sampler(record)
    sampler_mode = (
        sampler.get("mode")
        if isinstance(sampler, Mapping) and sampler.get("mode") in {"off", "default", "explicit"}
        else None
    )
    sampler_interval_seconds = (
        sampler.get("interval_seconds") if isinstance(sampler, Mapping) else None
    )
    mismatches.extend(
        validate_pair_analysis(
            outlier,
            timestamps=ctx.timestamps,
            aiclk_mhz=aiclk,
            sampler_mode=sampler_mode,
            sampler_interval_seconds=sampler_interval_seconds,
            strict_fields=not legacy,
        )
    )

    comparison = outlier.get("sampler_interval_comparison")
    if (
        isinstance(comparison, Mapping)
        and isinstance(sampler, Mapping)
        and sampler.get("mode") != "__mismatch__"
        and ("mode" in comparison or "interval_seconds" in comparison)
    ):
        if "mode" in comparison and comparison.get("mode") != sampler.get("mode"):
            mismatches.append(_mismatch("outlier_analysis", ("outlier_analysis.sampler_interval_comparison.mode", "telemetry_sampler.mode"), "sampler comparison mode does not match record sampler mode"))
        for comparison_field in ("interval_seconds", "sampler_interval_seconds"):
            if (
                comparison_field in comparison
                and comparison.get(comparison_field) != sampler.get("interval_seconds")
            ):
                mismatches.append(
                    _mismatch(
                        "outlier_analysis",
                        (
                            f"outlier_analysis.sampler_interval_comparison.{comparison_field}",
                            "telemetry_sampler.interval_seconds",
                        ),
                        "sampler comparison interval does not match record sampler interval",
                    )
                )
    return mismatches


def _check_ring(record: Mapping[str, Any], ctx: ValidationContext) -> list[dict[str, Any]]:
    invariant = "ring.counts"
    ring = _mapping(record, "ring")
    params = _mapping(record, "parameters")
    if ring is None:
        return [_mismatch(invariant, ("ring",), "ring must be an object")]
    if params is None:
        return [_mismatch(invariant, ("ring", "parameters"), "ring cannot be checked without parameters")]
    mismatches: list[dict[str, Any]] = []
    pairs = (
        ("attempted_frame_count", "attempted"),
        ("produced_frame_count", "produced"),
        ("dropped_frame_count", "dropped"),
        ("aborted_attempts", "aborted"),
    )
    for ring_name, parameter_name in pairs:
        ring_value = ring.get(ring_name, 0) if ring_name == "aborted_attempts" else ring.get(ring_name)
        param_value = params.get({"attempted": "attempted_frame_count", "produced": "produced_frame_count", "dropped": "dropped_frame_count", "aborted": "aborted_attempts"}[parameter_name], 0)
        if not _is_int(ring_value, nonnegative=True):
            mismatches.append(_mismatch(invariant, (f"ring.{ring_name}",), f"ring.{ring_name} must be a non-negative integer"))
        if _is_int(ring_value, nonnegative=True) and ring_value != param_value:
            mismatches.append(_mismatch(invariant, (f"ring.{ring_name}", f"parameters.{parameter_name}_frame_count"), f"ring.{ring_name} must equal parameters.{parameter_name}_frame_count"))
    for name in ("producer_full_count", "consumer_empty_count", "overflow_count"):
        if not _is_int(ring.get(name), nonnegative=True):
            mismatches.append(_mismatch(invariant, (f"ring.{name}",), f"ring.{name} must be a non-negative integer"))
    if _is_int(ring.get("producer_full_count"), nonnegative=True) and ring.get("producer_full_count") != params.get("dropped_frame_count"):
        mismatches.append(_mismatch(invariant, ("ring.producer_full_count", "parameters.dropped_frame_count"), "producer_full_count must equal dropped_frame_count"))
    if _is_int(ring.get("overflow_count"), nonnegative=True) and ring.get("overflow_count") != ring.get("producer_full_count"):
        mismatches.append(_mismatch(invariant, ("ring.overflow_count", "ring.producer_full_count"), "overflow_count must equal producer_full_count"))
    consumed = ring.get("consumed_frame_count")
    produced = ring.get("produced_frame_count")
    if not _is_int(consumed, nonnegative=True):
        mismatches.append(_mismatch(invariant, ("ring.consumed_frame_count",), "ring.consumed_frame_count must be a non-negative integer"))
    expected_consumed = len(ctx.timestamps) if ctx.timestamps is not None else _value(record, "raw_timestamps.count")
    if _is_int(consumed, nonnegative=True) and _is_int(expected_consumed, nonnegative=True) and consumed != expected_consumed:
        mismatches.append(_mismatch(invariant, ("ring.consumed_frame_count", "raw_timestamps.count"), "ring consumed_frame_count must equal raw timestamp count"))
    if _is_int(consumed, nonnegative=True) and _is_int(produced, nonnegative=True):
        if consumed > produced:
            mismatches.append(_mismatch(invariant, ("ring.consumed_frame_count", "ring.produced_frame_count"), "consumed_frame_count cannot exceed produced_frame_count"))
        ring_pages = params.get("ring_pages")
        if _is_int(ring_pages, nonnegative=True) and produced - consumed > ring_pages:
            mismatches.append(_mismatch(invariant, ("ring.produced_frame_count", "ring.consumed_frame_count", "parameters.ring_pages"), "ring occupancy produced-consumed exceeds ring_pages"))
    if "frames_consumed" in record and record.get("frames_consumed") != consumed:
        mismatches.append(_mismatch(invariant, ("frames_consumed", "ring.consumed_frame_count"), "top-level frames_consumed must equal ring consumed_frame_count"))
    return mismatches


def _sampler(record: Mapping[str, Any]) -> Mapping[str, Any] | None:
    top_present = "telemetry_sampler" in record
    top = record.get("telemetry_sampler")
    environment = record.get("environment")
    nested_present = isinstance(environment, Mapping) and "telemetry_sampler" in environment
    nested = environment.get("telemetry_sampler") if isinstance(environment, Mapping) else None
    if top_present and not isinstance(top, Mapping):
        return {"mode": "__mismatch__", "top": top, "nested": nested}
    if nested_present and not isinstance(nested, Mapping):
        return {"mode": "__mismatch__", "top": top, "nested": nested}
    if isinstance(top, Mapping) and isinstance(nested, Mapping):
        compared = ("mode", "interval_seconds", "power_trace", "timing_evidence")
        if any(top.get(key) != nested.get(key) for key in compared):
            return {"mode": "__mismatch__", "top": top, "nested": nested}
    if isinstance(top, Mapping):
        return top
    if isinstance(nested, Mapping):
        return nested
    return None


def _check_sampler_contract(record: Mapping[str, Any], ctx: ValidationContext) -> list[dict[str, Any]]:
    del ctx
    invariant = "sampler.trace_contract"
    sampler = _sampler(record)
    if sampler is None:
        return []
    if sampler.get("mode") == "__mismatch__":
        top = sampler.get("top")
        mode = top.get("mode") if isinstance(top, Mapping) else None
        if mode in {"default", "explicit"}:
            return [_mismatch(invariant, ("telemetry_sampler", "environment.telemetry_sampler"), "sampled sampler mode requires matching trace metadata")]
        return [_mismatch(invariant, ("telemetry_sampler", "environment.telemetry_sampler"), "top-level and environment sampler metadata disagree")]

    try:
        canonical = normalize_sampler_metadata(sampler, complete_default=False)
    except (TypeError, ValueError) as exc:
        field = (
            "telemetry_sampler.interval_seconds"
            if "interval" in str(exc)
            else "telemetry_sampler.mode"
        )
        return [_mismatch(invariant, (field,), f"sampler contract violation: {exc}")]

    mode = canonical["mode"]
    contract = SAMPLER_CONTRACT[mode]
    trace_name = record.get("power_trace")
    mismatches: list[dict[str, Any]] = []
    if sampler.get("power_trace") != contract["power_trace"]:
        mismatches.append(_mismatch(invariant, ("telemetry_sampler.power_trace",), "sampler power_trace metadata does not match sampler mode"))
    if sampler.get("timing_evidence") != contract["timing_evidence"]:
        mismatches.append(_mismatch(invariant, ("telemetry_sampler.timing_evidence",), "sampler timing_evidence metadata does not match sampler mode"))
    if mode == "off":
        if trace_name is not None:
            mismatches.append(_mismatch(invariant, ("power_trace", "telemetry_sampler.mode"), "sampler-off records must omit the power trace"))
        if record.get("power_trace_absent_reason") != "sampler_off_by_design":
            mismatches.append(_mismatch(invariant, ("power_trace_absent_reason",), "sampler-off records require sampler_off_by_design"))
    else:
        if not isinstance(trace_name, str) or not trace_name.strip() or Path(trace_name).name != trace_name:
            mismatches.append(_mismatch(invariant, ("power_trace", "telemetry_sampler.mode"), "sampled sampler mode requires a power trace basename"))
    return mismatches



def _force_timing_false(record: dict[str, Any], reason: str) -> None:
    record["timing_evidence"] = False
    record["timing_evidence_reason"] = reason
    provenance = record.get("power_clock_provenance")
    if isinstance(provenance, dict):
        provenance["timing_evidence"] = False
        provenance["timing_evidence_reason"] = reason


def _apply_builder_timing_policy(
    record: dict[str, Any], ctx: ValidationContext, report: Mapping[str, Any] | None
) -> None:
    """Force unsafe builder claims false without weakening numeric checks."""
    timing_kind = _timing_record_kind(record)
    if timing_kind == RECORD_KIND_ERROR:
        _force_timing_false(record, TIMING_EVIDENCE_ERROR_RECORD_REASON)
        return
    if timing_kind == RECORD_KIND_REJECTED:
        _force_timing_false(record, TIMING_EVIDENCE_REJECTED_RECORD_REASON)
        return
    reason = _timing_block_reason(record, ctx, report)
    timing = record.get("timing_evidence")
    if reason is not None and timing is True:
        _force_timing_false(record, reason)
    elif timing is False:
        current_reason = record.get("timing_evidence_reason")
        if not isinstance(current_reason, str) or not current_reason.strip() or current_reason in {
            TIMING_EVIDENCE_RUN_TRACE_REASON,
            "timing",
        }:
            record["timing_evidence_reason"] = reason or TIMING_EVIDENCE_NOT_REQUESTED
            provenance = record.get("power_clock_provenance")
            if isinstance(provenance, dict):
                provenance["timing_evidence_reason"] = record["timing_evidence_reason"]


def _out_of_scope_report(record: Mapping[str, Any]) -> dict[str, Any]:
    """Report records written outside the current runner validation scope."""
    actual_marker = record.get("resident_record_schema", _MISSING)
    marker_text = "missing" if actual_marker is _MISSING else repr(actual_marker)
    return {
        "valid": None,
        "out_of_scope": True,
        "classification": "out_of_scope",
        "reason": (
            "resident_record_schema marker must be "
            f"{RESIDENT_RECORD_SCHEMA_MARKER}; got {marker_text}"
        ),
        "resident_record_schema": (
            None if actual_marker is _MISSING else actual_marker
        ),
        "expected_resident_record_schema": RESIDENT_RECORD_SCHEMA_MARKER,
        "timing_evidence": None,
        "mismatches": [],
        "failures": [],
        "warnings": [],
        "warning_fields": [],
        "checks": {},
        "catalog": [
            {"name": entry.name, "fields": list(entry.fields), "description": entry.description}
            for entry in RESIDENT_INVARIANT_CATALOG
        ],
        "power_trace": None,
    }


def validate_resident_record(
    record: Mapping[str, Any],
    *,
    raw_metadata: Mapping[str, Any] | None = None,
    timestamps: Iterable[int] | None = None,
    power_trace_path: Path | None = None,
    power_trace_metadata: Mapping[str, Any] | None = None,
    power_trace_bytes: bytes | None = None,
    raw_bytes: bytes | None = None,
    builder: bool = False,
    strict_trace: bool = True,
    raise_on_error: bool | None = None,
) -> dict[str, Any]:
    """Validate one current-runner record through the invariant catalog.

    Records without the current ``resident_record_schema`` marker are returned
    as ``out_of_scope`` without running the catalog.  For marked records, the
    modern record-kind field matrix runs before value and relationship checks;
    unknown telemetry and production paths are retained as warnings, while
    required declared fields and major relationships remain hard failures.
    Analyzer callers use the default report mode.  Builder callers pass
    ``builder=True`` and may use ``raise_on_error=True`` for hard numeric or
    schema contradictions; unsafe timing claims are changed to false with an
    explicit reason before the report is produced.
    """
    if raise_on_error is None:
        raise_on_error = builder
    if not isinstance(record, Mapping):
        report = {
            "valid": False,
            "mismatches": [_mismatch("record", ("record",), "record must be an object")],
            "failures": ["record must be an object"],
            "warnings": [],
            "warning_fields": [],
            "checks": {},
            "catalog": [entry.name for entry in RESIDENT_INVARIANT_CATALOG],
            "power_trace": None,
        }
        if raise_on_error:
            raise ValueError("record must be an object")
        return report
    if (
        type(record.get("resident_record_schema")) is not int
        or record.get("resident_record_schema") != RESIDENT_RECORD_SCHEMA_MARKER
    ):
        return _out_of_scope_report(record)
    timestamp_values = list(timestamps) if timestamps is not None else None
    if raw_metadata is None and raw_bytes is not None:
        raw_metadata = {
            "count": len(raw_bytes) // 8 if len(raw_bytes) % 8 == 0 else -1,
            "sha256": hashlib.sha256(raw_bytes).hexdigest(),
        }
    ctx = ValidationContext(
        timestamps=timestamp_values,
        raw_metadata=raw_metadata,
        power_trace_path=Path(power_trace_path) if power_trace_path is not None else None,
        power_trace_metadata=power_trace_metadata,
        power_trace_bytes=power_trace_bytes,
        strict_trace=strict_trace,
        builder=builder,
    )
    trace_report = _trace_report(record, ctx)
    mismatches: list[dict[str, Any]] = []
    warnings: list[dict[str, Any]] = []
    checks: dict[str, Any] = {}
    record_kind = _record_kind(record)
    if builder and isinstance(record, dict):
        _apply_builder_timing_policy(record, ctx, trace_report)
    for entry in RESIDENT_INVARIANT_CATALOG:
        try:
            if record_kind == RECORD_KIND_REJECTED and entry.name not in {
                "record.required_fields",
                "record.field_values",
                "record.unknown_fields",
                "clock_source_evidence",
                "failure_check",
                "cycle_budget",
                "clock.timing_evidence",
            }:
                entry_mismatches = []
            else:
                entry_mismatches = entry.check(record, ctx)
        except (TypeError, ValueError, KeyError, IndexError) as exc:
            entry_mismatches = [_mismatch(entry.name, entry.fields, f"malformed input: {exc}")]
        entry_warnings = [item for item in entry_mismatches if item.get("soft") is True]
        entry_mismatches = [item for item in entry_mismatches if item.get("soft") is not True]
        checks[entry.name] = {
            "ok": not entry_mismatches,
            "fields": list(entry.fields),
            "description": entry.description,
            "mismatches": entry_mismatches,
            "warnings": entry_warnings,
        }
        warnings.extend(entry_warnings)
        mismatches.extend(entry_mismatches)
    if (
        builder
        and isinstance(record, dict)
        and record.get("timing_evidence") is True
        and mismatches
    ):
        _force_timing_false(record, "record_validation_failed")
    warning_fields = sorted(
        {field for warning in warnings for field in warning.get("fields", ())}
    )
    failures = [item["message"] for item in mismatches]
    if builder and isinstance(record, dict):
        record["validation_warnings"] = warning_fields
    # Preserve the historic check names consumed by board-free callers while
    # keeping their implementation in the catalog entries above.
    if "histogram" in checks:
        checks["histogram_n_plus_one"] = checks["histogram"]
        checks["histogram_bins"] = checks["histogram"]
    if "outlier_analysis" in checks:
        checks["pair_catalog"] = checks["outlier_analysis"]
    if "power_trace.facts" in checks:
        checks["power_trace"] = checks["power_trace.facts"]
    if "clock.timing_evidence" in checks:
        checks["timing_evidence"] = checks["clock.timing_evidence"]
    report: dict[str, Any] = {
        "valid": not mismatches,
        "out_of_scope": False,
        "classification": "in_scope",
        "mismatches": mismatches,
        "failures": failures,
        "warnings": warnings,
        "warning_fields": warning_fields,
        "checks": checks,
        "catalog": [
            {"name": entry.name, "fields": list(entry.fields), "description": entry.description}
            for entry in RESIDENT_INVARIANT_CATALOG
        ],
        "power_trace": trace_report,
    }
    if raise_on_error and mismatches:
        trace_unusable = (
            builder
            and trace_report is not None
            and (
                trace_report.get("readable") is not True
                or trace_report.get("coverage_complete") is not True
                or trace_report.get("aiclk_source") != "run_trace_samples"
            )
        )
        hard = [
            item
            for item in mismatches
            if not (
                item["invariant"] == "power_trace.facts"
                and (
                    trace_unusable
                    or "unavailable" in item["message"]
                    or "not true" in item["message"]
                    or "not readable" in item["message"]
                    or "coverage_complete" in item["message"]
                    or "valid-row" in item["message"]
                    or "row count" in item["message"]
                    or "columns" in item["message"]
                )
            )
            and item["invariant"] != "clock.timing_evidence"
        ]
        if hard:
            raise ValueError(hard[0]["message"])
    return report



# callers.  The implementation remains in this module, not in the analyzer.
_detect_pairs = detect_pairs


def _count_orders(pairs: Iterable[Mapping[str, Any]]) -> dict[str, int]:
    counts = Counter({order: 0 for order in PAIR_ORDERS})
    for pair in pairs:
        order = pair.get("order")
        if order not in counts:
            counts["other"] += 1
        else:
            counts[str(order)] += 1
    return {order: counts[order] for order in PAIR_ORDERS}


def _duplicate_values(values: Iterable[int]) -> list[int]:
    return sorted(value for value, count in Counter(values).items() if count > 1)


def _counter_difference(left: Iterable[int], right: Iterable[int]) -> list[int]:
    return sorted((Counter(left) - Counter(right)).elements())


def _ordered_mismatches(left: list[Any], right: list[Any]) -> list[int]:
    return [
        index
        for index in range(min(len(left), len(right)))
        if left[index] != right[index]
    ]


def _record_pair_starts(record: Mapping[str, Any]) -> list[int]:
    outlier = record.get("outlier_analysis")
    if not isinstance(outlier, Mapping):
        return []
    starts = outlier.get("frame_start_indices", _MISSING)
    pair_count = outlier.get("pair_count")
    pair_sums = outlier.get("pair_sums")
    if starts is _MISSING:
        if type(pair_count) is int and pair_count == 0 and isinstance(pair_sums, list) and not pair_sums:
            return []
        return []
    return list(starts) if isinstance(starts, list) else []


def _record_pairs(record: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    outlier = record.get("outlier_analysis")
    if not isinstance(outlier, Mapping):
        return []
    pairs = outlier.get("pairs", [])
    return list(pairs) if isinstance(pairs, list) else []


def record_correspondence(
    detected_pairs: list[Mapping[str, Any]], record: Mapping[str, Any]
) -> dict[str, Any]:
    """Compare recorded and raw-derived pairs by length, multiset, and order."""
    detected_endpoints = [pair.get("interval_end_frame_indices") for pair in detected_pairs]
    record_starts = _record_pair_starts(record)
    record_pairs = _record_pairs(record)
    record_endpoints = [
        pair.get("interval_end_frame_indices") for pair in record_pairs if isinstance(pair, Mapping)
    ]
    detected_starts = [
        endpoints[0]
        for endpoints in detected_endpoints
        if isinstance(endpoints, list) and endpoints
    ]

    missing = _counter_difference(record_starts, detected_starts)
    unexpected = _counter_difference(detected_starts, record_starts)
    record_duplicate_starts = _duplicate_values(record_starts)
    raw_duplicate_starts = _duplicate_values(detected_starts)
    frame_start_length_match = len(record_starts) == len(detected_starts)
    frame_start_multiset_match = not missing and not unexpected
    frame_start_order_mismatches = _ordered_mismatches(record_starts, detected_starts)
    frame_start_order_match = frame_start_length_match and not frame_start_order_mismatches
    exact_frame_start_match = (
        frame_start_length_match
        and frame_start_multiset_match
        and frame_start_order_match
        and not record_duplicate_starts
    )

    endpoint_mismatches = _ordered_mismatches(detected_endpoints, record_endpoints)
    endpoint_length_match = len(detected_endpoints) == len(record_endpoints)
    missing_endpoint_indices = list(range(len(record_endpoints), len(detected_endpoints)))
    unexpected_endpoint_indices = list(range(len(detected_endpoints), len(record_endpoints)))

    common_pair_count = min(len(detected_pairs), len(record_pairs))
    order_mismatches: list[int] = []
    value_mismatches: list[int] = []
    sum_mismatches: list[int] = []
    for index in range(common_pair_count):
        detected = detected_pairs[index]
        recorded = record_pairs[index]
        if recorded.get("order") is not None and recorded.get("order") != detected.get("order"):
            order_mismatches.append(index)
        if (
            recorded.get("short_ticks") is not None
            and recorded.get("short_ticks") != detected.get("short_ticks")
        ) or (
            recorded.get("long_ticks") is not None
            and recorded.get("long_ticks") != detected.get("long_ticks")
        ):
            value_mismatches.append(index)
        if (
            recorded.get("pair_sum_ticks") is not None
            and recorded.get("pair_sum_ticks") != detected.get("pair_sum_ticks")
        ):
            sum_mismatches.append(index)
    missing_pair_indices = list(range(len(record_pairs), len(detected_pairs)))
    unexpected_pair_indices = list(range(len(detected_pairs), len(record_pairs)))

    return {
        "record_pair_count": len(record_starts),
        "raw_derived_pair_count": len(detected_pairs),
        "record_frame_start_indices": record_starts,
        "raw_derived_frame_start_indices": detected_starts,
        "exact_frame_start_match": exact_frame_start_match,
        "missing_raw_pair_starts": missing,
        "unexpected_raw_pair_starts": unexpected,
        "frame_start_length_match": frame_start_length_match,
        "frame_start_length_mismatch": not frame_start_length_match,
        "frame_start_lengths": {"record": len(record_starts), "raw_derived": len(detected_starts)},
        "record_duplicate_frame_start_indices": record_duplicate_starts,
        "raw_derived_duplicate_frame_start_indices": raw_duplicate_starts,
        "frame_start_multiset_match": frame_start_multiset_match,
        "frame_start_order_match": frame_start_order_match,
        "frame_start_order_mismatches": frame_start_order_mismatches,
        "record_pair_list_count": len(record_pairs),
        "record_pair_list_length_match": len(record_pairs) == len(detected_pairs),
        "record_pair_list_length_mismatch": len(record_pairs) != len(detected_pairs),
        "record_pair_endpoints_present": (
            len(record_endpoints) == len(record_pairs)
            and all(endpoint is not None for endpoint in record_endpoints)
        ),
        "pair_endpoint_list_length_match": endpoint_length_match,
        "pair_endpoint_list_length_mismatch": not endpoint_length_match,
        "pair_endpoint_list_lengths": {
            "record": len(record_endpoints),
            "raw_derived": len(detected_endpoints),
        },
        "pair_endpoint_missing_record_indices": missing_endpoint_indices,
        "pair_endpoint_unexpected_record_indices": unexpected_endpoint_indices,
        "pair_endpoint_mismatches": endpoint_mismatches,
        "pair_endpoint_order_mismatches": endpoint_mismatches,
        "pair_order_mismatches": order_mismatches,
        "pair_order_missing_record_indices": missing_pair_indices,
        "pair_order_unexpected_record_indices": unexpected_pair_indices,
        "pair_value_mismatches": value_mismatches,
        "pair_value_missing_record_indices": missing_pair_indices,
        "pair_value_unexpected_record_indices": unexpected_pair_indices,
        "pair_sum_mismatches": sum_mismatches,
        "pair_sum_missing_record_indices": missing_pair_indices,
        "pair_sum_unexpected_record_indices": unexpected_pair_indices,
    }


_record_correspondence = record_correspondence


def _gcd(values: Iterable[int]) -> int | None:
    result = 0
    found = False
    for value in values:
        result = math.gcd(result, value)
        found = True
    return result if found else None


def _sampler_comparison(
    *,
    sampler_mode: str | None,
    sampler_interval_seconds: float | None,
    timestamps: list[int],
    pair_starts: list[int],
    aiclk_selection: Mapping[str, Any],
) -> dict[str, Any]:
    """Return numeric sampler-gap measurements without a prose conclusion."""
    pair_count = len(pair_starts)
    frame_count = len(timestamps)
    adjacent_gaps: list[dict[str, Any]] = []
    if sampler_mode in {"default", "explicit"}:
        if sampler_interval_seconds is None:
            raise ValueError("sampled sampler metadata must include an interval")
        sampler_interval = _finite_float(
            sampler_interval_seconds, "sampler interval seconds"
        )
        for from_frame, to_frame in itertools.pairwise(pair_starts):
            gap_frames = to_frame - from_frame
            gap_elapsed_seconds = ticks_to_seconds(
                ticks=timestamps[to_frame] - timestamps[from_frame],
                selection=aiclk_selection,
            )
            sampler_intervals = _finite_float(
                gap_elapsed_seconds / sampler_interval,
                "sampler intervals",
            )
            nearest_integer = round(sampler_intervals)
            residual = _finite_float(
                gap_elapsed_seconds - nearest_integer * sampler_interval,
                "sampler residual seconds",
            )
            adjacent_gaps.append(
                {
                    "from_pair_start_frame": from_frame,
                    "gap_elapsed_seconds": gap_elapsed_seconds,
                    "gap_frames": gap_frames,
                    "nearest_integer_sampler_intervals": nearest_integer,
                    "residual_to_nearest_sampler_multiple_seconds": residual,
                    "sampler_intervals": sampler_intervals,
                    "to_pair_start_frame": to_frame,
                }
            )
        return {
            "mode": sampler_mode,
            "interval_seconds": sampler_interval,
            "sampler_interval_seconds": sampler_interval,
            "pair_count": pair_count,
            "timestamp_count": frame_count,
            "adjacent_gaps": adjacent_gaps,
        }
    return {
        "mode": sampler_mode,
        "interval_seconds": None,
        "sampler_interval_seconds": None,
        "pair_count": pair_count,
        "timestamp_count": frame_count,
        "adjacent_gaps": adjacent_gaps,
    }


def build_outlier_analysis(
    timestamps: Iterable[int],
    *,
    aiclk_mhz: int = DEFAULT_AICLK_MHZ,
    aiclk_source: str | None = None,
    elapsed_aiclk_mhz: float | None = None,
    elapsed_aiclk_source: str | None = None,
    sampler_mode: str | None = None,
    sampler_interval_seconds: float | None = None,
    sampler_metadata: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Build the canonical outlier catalog from timestamps and run metadata."""
    if not _is_int(aiclk_mhz, positive=True):
        raise ValueError("aiclk_mhz must be a positive integer")
    if sampler_metadata is not None:
        if sampler_mode is not None or sampler_interval_seconds is not None:
            raise ValueError("sampler metadata cannot be combined with sampler mode arguments")
        sampler = normalize_sampler_metadata(sampler_metadata)
        sampler_mode = sampler["mode"]
        sampler_interval_seconds = sampler["interval_seconds"]
    elif sampler_mode is not None:
        sampler = normalize_sampler_metadata(
            {
                "mode": sampler_mode,
                "interval_seconds": sampler_interval_seconds,
            }
        )
        sampler_mode = sampler["mode"]
        sampler_interval_seconds = sampler["interval_seconds"]
    selection_mode = sampler_mode or "off"
    selected_source = aiclk_source or (
        AICLK_SOURCE_CONFIGURED
        if selection_mode == "off"
        else AICLK_SOURCE_RUN_TRACE_SAMPLES
    )
    aiclk_selection = select_elapsed_aiclk(
        budget_aiclk_mhz=aiclk_mhz,
        sampler_mode=selection_mode,
        trace_aiclk_mhz=(
            aiclk_mhz
            if selection_mode != "off" and selected_source == AICLK_SOURCE_RUN_TRACE_SAMPLES
            else None
        ),
        trace_aiclk_source=(
            selected_source
            if selection_mode != "off" and selected_source == AICLK_SOURCE_RUN_TRACE_SAMPLES
            else None
        ),
        legacy_aiclk_mhz=(
            aiclk_mhz
            if selection_mode != "off"
            and selected_source
            not in {
                AICLK_SOURCE_CONFIGURED,
                AICLK_SOURCE_RUN_TRACE_SAMPLES,
                "no_valid_in_run_samples",
            }
            else None
        ),
        legacy_aiclk_source=selected_source,
        allow_configured_fallback=(
            selection_mode != "off" and selected_source == AICLK_SOURCE_CONFIGURED
        ),
    )
    selected_source = aiclk_selection["aiclk_source"]
    elapsed_selection = aiclk_selection
    if elapsed_aiclk_mhz is not None:
        if not isinstance(elapsed_aiclk_mhz, (int, float)) or isinstance(
            elapsed_aiclk_mhz, bool
        ) or not math.isfinite(float(elapsed_aiclk_mhz)) or elapsed_aiclk_mhz <= 0:
            raise ValueError("elapsed_aiclk_mhz must be a finite positive number")
        elapsed_source = elapsed_aiclk_source or "explicit_elapsed_aiclk"
        elapsed_selection = {
            "aiclk_mhz": float(elapsed_aiclk_mhz),
            "aiclk_mhz_exact": float(elapsed_aiclk_mhz),
            "aiclk_source": elapsed_source,
        }
    values = list(timestamps)
    if any(not _is_int(value, nonnegative=True) for value in values):
        raise ValueError("timestamps must contain unsigned integer values")
    if any(current <= previous for previous, current in itertools.pairwise(values)):
        raise ValueError("timestamps must be strictly increasing")
    pairs = detect_pairs(values)
    starts = [pair["interval_end_frame_indices"][0] for pair in pairs]
    endpoints = [endpoint for pair in pairs for endpoint in pair["interval_end_frame_indices"]]
    elapsed_ticks = [values[index] - values[0] for index in endpoints]
    elapsed_mod = [elapsed % CLOCK_MODULUS_TICKS for elapsed in elapsed_ticks]
    elapsed_seconds = [
        ticks_to_seconds(ticks=elapsed, selection=elapsed_selection)
        for elapsed in elapsed_ticks
    ]
    pair_start_elapsed_seconds = [
        ticks_to_seconds(
            ticks=values[index] - values[0], selection=elapsed_selection
        )
        for index in starts
    ]
    for pair in pairs:
        first_endpoint = pair["interval_end_frame_indices"][0]
        first_elapsed = values[first_endpoint] - values[0]
        pair["first_interval_end_elapsed_seconds"] = ticks_to_seconds(
            ticks=first_elapsed,
            selection=elapsed_selection,
        )
    pair_sums = [pair["pair_sum_ticks"] for pair in pairs]
    gaps = [right - left for left, right in itertools.pairwise(starts)]
    gap_counts = Counter(gaps)
    gap_histogram = [
        {"gap_frames": gap, "count": gap_counts[gap]} for gap in sorted(gap_counts)
    ]
    pair_order_counts = _count_orders(pairs)
    sum_deltas = [pair - PAIR_TARGET_TICKS for pair in pair_sums]
    intervals = [current - previous for previous, current in itertools.pairwise(values)]
    return {
        "method": (
            "short < 1250000 ticks, long > 1450000 ticks, "
            "adjacent pair sum within 1000 ticks of 2700000"
        ),
        "pair_count": len(pairs),
        "pair_sum_target_ticks": PAIR_TARGET_TICKS,
        "pair_sums": pair_sums,
        "pair_sum_min_ticks": min(pair_sums) if pair_sums else None,
        "pair_sum_max_ticks": max(pair_sums) if pair_sums else None,
        "pair_sum_mean_ticks": (
            _finite_ratio(sum(pair_sums), len(pair_sums), "pair sum mean ticks")
            if pair_sums
            else None
        ),
        "sum_delta_min_ticks": min(sum_deltas) if sum_deltas else None,
        "sum_delta_max_ticks": max(sum_deltas) if sum_deltas else None,
        "pair_order_counts": pair_order_counts,
        "frame_start_indices": starts,
        "event_frame_positions": endpoints,
        "event_elapsed_seconds": elapsed_seconds,
        "event_elapsed_ticks": elapsed_ticks,
        "event_elapsed_ticks_mod_period": elapsed_mod,
        "pair_start_elapsed_seconds": pair_start_elapsed_seconds,
        "frame_gaps": gaps,
        "gap_counts": {str(gap): gap_counts[gap] for gap in sorted(gap_counts)},
        "gap_histogram": gap_histogram,
        "gcd_frame_gap": _gcd(gaps),
        "pairs": pairs,
        "elapsed_time_unit": "seconds",
        "device_tick_unit": "device_clock_ticks",
        "aiclk_mhz_for_elapsed_seconds": elapsed_selection["aiclk_mhz"],
        "aiclk_source": selected_source,
        "aiclk_source_for_elapsed_seconds": elapsed_selection["aiclk_source"],
        "aiclk_selection_for_elapsed_seconds": aiclk_selection_for_source(
            elapsed_selection["aiclk_source"]
        ),
        "run_elapsed_ticks": values[-1] - values[0] if values else 0,
        "run_elapsed_seconds": (
            ticks_to_seconds(
                ticks=values[-1] - values[0], selection=elapsed_selection
            )
            if values
            else 0.0
        ),
        "interval_count": len(intervals),
        "sampler_interval_comparison": _sampler_comparison(
            sampler_mode=sampler_mode,
            sampler_interval_seconds=sampler_interval_seconds,
            timestamps=values,
            pair_starts=starts,
            aiclk_selection=elapsed_selection,
        ),
    }



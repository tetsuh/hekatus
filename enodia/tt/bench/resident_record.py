def _trace_coverage_inputs(
    trace_name: str,
    declared: Mapping[str, Any],
    sampler_interval: Any,
) -> tuple[str, Any, dict[str, Any] | None]:
    coverage_definition = declared.get(
        "coverage_definition", EXPLICIT_FINAL_SAMPLE
    )
    if not is_coverage_definition(coverage_definition):
        coverage_definition = EXPLICIT_FINAL_SAMPLE
    if coverage_definition != ONE_INTERVAL_BOUND:
        return coverage_definition, sampler_interval, None
    try:
        interval = float(sampler_interval)
    except (TypeError, ValueError, OverflowError):
        return (
            coverage_definition,
            sampler_interval,
            _invalid_trace_report(
                trace_name=trace_name,
                coverage_definition=coverage_definition,
                sampler_interval=sampler_interval,
                error="one_interval_bound requires a finite positive sampler interval",
            ),
        )
    if not math.isfinite(interval) or interval <= 0.0:
        return (
            coverage_definition,
            sampler_interval,
            _invalid_trace_report(
                trace_name=trace_name,
                coverage_definition=coverage_definition,
                sampler_interval=sampler_interval,
                error="one_interval_bound requires a finite positive sampler interval",
            ),
        )
    return coverage_definition, interval, None


def _trace_report_from_path(
    ctx: ValidationContext,
    *,
    trace_name: str,
    run_start: Any,
    run_end: Any,
    load_interval_start: Any,
    load_interval_end: Any,
    load_interval_source: Any,
    require_explicit_load_interval: bool,
    coverage_definition: str,
    sampler_interval: Any,
    interval_extrema_policy: Any,
) -> dict[str, Any]:
    try:
        report = read_power_trace_csv(
            ctx.power_trace_path,
            options=PowerTraceCsvOptions(
                run_start=None if run_start is _MISSING else run_start,
                run_end=None if run_end is _MISSING else run_end,
                coverage_definition=coverage_definition,
                sampler_interval_seconds=sampler_interval,
                load_interval_start=(
                    None if load_interval_start is _MISSING else load_interval_start
                ),
                load_interval_end=(
                    None if load_interval_end is _MISSING else load_interval_end
                ),
                load_interval_source=(
                    None if load_interval_source is _MISSING else load_interval_source
                ),
                require_explicit_load_interval=require_explicit_load_interval,
                require_all_rows_valid=True,
                immutable_snapshot=(
                    interval_extrema_policy
                    == INTERVAL_EXTREMA_POLICY_POSITIVE_DURATION_LEFT_HELD
                ),
                reject_incomplete_rows=False,
            ),
        )
        report = public_power_trace_metadata(report)
    except (TypeError, ValueError, OverflowError) as exc:
        return _invalid_trace_report(
            trace_name=trace_name,
            coverage_definition=coverage_definition,
            sampler_interval=sampler_interval,
            error=exc,
        )
    report["actual_bytes_available"] = True
    return report


def _trace_report_from_context(
    ctx: ValidationContext,
    *,
    trace_name: str,
    coverage_definition: str,
    sampler_interval: Any,
    run_start: Any,
    run_end: Any,
    load_interval_start: Any,
    load_interval_end: Any,
    load_interval_source: Any,
    require_explicit_load_interval: bool,
    interval_extrema_policy: Any,
) -> dict[str, Any]:
    if ctx.power_trace_path is not None:
        return _trace_report_from_path(
            ctx,
            trace_name=trace_name,
            run_start=run_start,
            run_end=run_end,
            load_interval_start=load_interval_start,
            load_interval_end=load_interval_end,
            load_interval_source=load_interval_source,
            require_explicit_load_interval=require_explicit_load_interval,
            coverage_definition=coverage_definition,
            sampler_interval=sampler_interval,
            interval_extrema_policy=interval_extrema_policy,
        )
    if ctx.power_trace_metadata is not None:
        report = dict(ctx.power_trace_metadata)
        report.setdefault("file", trace_name)
        report.setdefault("coverage_definition", coverage_definition)
        report["actual_bytes_available"] = False
        return report
    if ctx.power_trace_bytes is not None:
        return {
            "file": trace_name,
            "sha256": hashlib.sha256(ctx.power_trace_bytes).hexdigest(),
            "actual_bytes_available": True,
            "readable": False,
            "coverage_complete": False,
            "coverage_definition": coverage_definition,
            "aiclk_source": "no_valid_in_run_samples",
        }
    return {"file": trace_name, "actual_bytes_available": False, "reason": "power_trace_bytes_unavailable"}


def _trace_report(record: Mapping[str, Any], ctx: ValidationContext) -> dict[str, Any] | None:
    sampler = _sampler(record)
    mode = sampler.get("mode") if isinstance(sampler, Mapping) else None
    trace_name = record.get("power_trace")
    if mode not in {"default", "explicit"} or not trace_name:
        return None
    declared = _declared_power_metadata(record)
    load = record.get("load")
    require_explicit_load_interval = (
        isinstance(load, Mapping)
        and load.get("condition") in {"newton_schulz", "dram"}
    )
    sampler_interval = (
        sampler.get("interval_seconds") if isinstance(sampler, Mapping) else None
    )
    coverage_definition, sampler_interval, invalid_report = _trace_coverage_inputs(
        trace_name, declared, sampler_interval
    )
    if invalid_report is not None:
        return invalid_report
    return _trace_report_from_context(
        ctx,
        trace_name=trace_name,
        coverage_definition=coverage_definition,
        sampler_interval=sampler_interval,
        run_start=declared.get("run_start"),
        run_end=declared.get("run_end"),
        load_interval_start=declared.get("load_interval_start", _MISSING),
        load_interval_end=declared.get("load_interval_end", _MISSING),
        load_interval_source=declared.get("load_interval_source", _MISSING),
        require_explicit_load_interval=require_explicit_load_interval,
        interval_extrema_policy=declared.get("interval_extrema_policy", _MISSING),
    )


def _trace_flag_mismatches(
    container: Mapping[str, Any] | None,
    prefix: str,
    aliases: tuple[tuple[str, str], ...],
    actual: Mapping[str, Any],
    invariant: str,
) -> list[dict[str, Any]]:
    """Compare every declared boolean alias with one recomputed trace fact."""
    if not isinstance(container, Mapping):
        return []
    mismatches: list[dict[str, Any]] = []
    for declared_name, actual_name in aliases:
        if declared_name not in container:
            continue
        declared = container.get(declared_name)
        expected = actual.get(actual_name, _MISSING)
        if (
            expected is not _MISSING
            and (
                type(declared) is not bool
                or type(expected) is not bool
                or declared is not expected
            )
        ):
            mismatches.append(
                _mismatch(
                    invariant,
                    (f"{prefix}.{declared_name}",),
                    f"{prefix}.{declared_name} does not match recomputed power-trace coverage",
                )
            )
    return mismatches


def _check_declared_trace_flags(
    record: Mapping[str, Any], report: Mapping[str, Any]
) -> list[dict[str, Any]]:
    """Bind top-level and nested coverage/provenance flags to CSV facts."""
    actual_coverage = report.get("coverage")
    if not isinstance(actual_coverage, Mapping):
        actual_coverage = {}
    invariant = "power_trace.coverage_flags"
    provenance = record.get("power_clock_provenance")
    trace_coverage = record.get("power_trace_coverage")
    mismatches = _trace_flag_mismatches(
        provenance if isinstance(provenance, Mapping) else None,
        "power_clock_provenance",
        _TRACE_TOP_FLAG_ALIASES,
        report,
        invariant,
    )
    provenance_coverage = (
        provenance.get("coverage")
        if isinstance(provenance, Mapping)
        else None
    )
    mismatches.extend(
        _trace_flag_mismatches(
            provenance_coverage,
            "power_clock_provenance.coverage",
            _TRACE_COVERAGE_FLAG_ALIASES,
            {**report, **actual_coverage},
            invariant,
        )
    )
    if isinstance(trace_coverage, Mapping):
        mismatches.extend(
            _trace_flag_mismatches(
                trace_coverage,
                "power_trace_coverage",
                _TRACE_RECORD_COVERAGE_FLAG_ALIASES,
                report,
                invariant,
            )
        )
        mismatches.extend(
            _trace_flag_mismatches(
                trace_coverage.get("coverage"),
                "power_trace_coverage.coverage",
                _TRACE_COVERAGE_FLAG_ALIASES,
                {**report, **actual_coverage},
                invariant,
            )
        )
    return mismatches


def _check_power_trace_facts(record: Mapping[str, Any], ctx: ValidationContext) -> list[dict[str, Any]]:
    invariant = "power_trace.facts"
    sampler = _sampler(record)
    mode = sampler.get("mode") if isinstance(sampler, Mapping) else None
    if mode == "off":
        if not _is_modern_record(record):
            return []
        declared = _declared_power_metadata(record)
        mismatches: list[dict[str, Any]] = []
        provenance = _mapping(record, "power_clock_provenance")
        if provenance is not None and provenance.get("trace") != provenance.get("file"):
            mismatches.append(
                _mismatch(
                    invariant,
                    ("power_clock_provenance.trace", "power_clock_provenance.file"),
                    "power provenance trace must equal file",
                )
            )
        expected_top = {
            "file": None,
            "sample_count": 0,
            "csv_row_count": 0,
            "valid_row_count": 0,
            "in_run_valid_row_count": 0,
            "sha256": None,
        }
        for field, expected in expected_top.items():
            actual = declared.get(field, _MISSING)
            if actual != expected:
                mismatches.append(
                    _mismatch(
                        invariant,
                        (f"power_clock_provenance.{field}",),
                        f"sampler-off power trace {field} must be {expected!r}",
                    )
                )
        if provenance is not None:
            for field, expected in {
                "file": None,
                "sha256": None,
                "readable": False,
                "nonempty": False,
                "csv_row_count": 0,
                "sample_count": 0,
                "valid_row_count": 0,
                "in_run_valid_row_count": 0,
                "timestamps_parse": False,
                "timestamps_ordered": False,
                "covers_run_start": False,
                "covers_run_end": False,
                "coverage_complete": False,
                "aiclk_source": "sampler_off_diagnostic",
                "aiclk_mhz": None,
            }.items():
                if provenance.get(field) != expected:
                    mismatches.append(
                        _mismatch(
                            invariant,
                            (f"power_clock_provenance.{field}",),
                            f"sampler-off power trace {field} must be {expected!r}",
                        )
                    )
        return mismatches
    if mode not in {"default", "explicit"} or not record.get("power_trace"):
        return []
    declared = _declared_power_metadata(record)
    report = _trace_report(record, ctx)
    if report is None:
        return []
    mismatches: list[dict[str, Any]] = []
    if not is_coverage_definition(declared.get("coverage_definition")):
        mismatches.append(
            _mismatch(
                invariant,
                (
                    _POWER_TRACE_COVERAGE_DEFINITION_PATH,
                    _POWER_CLOCK_COVERAGE_DEFINITION_PATH,
                ),
                "power trace coverage_definition is not a supported named definition",
            )
        )
    provenance = _mapping(record, "power_clock_provenance")
    if provenance is not None and provenance.get("trace") != provenance.get("file"):
        mismatches.append(
            _mismatch(
                invariant,
                ("power_clock_provenance.trace", "power_clock_provenance.file"),
                "power provenance trace must equal file",
            )
        )
    trace_name = record.get("power_trace")
    if declared.get("file", _MISSING) not in {_MISSING, None, trace_name}:
        mismatches.append(_mismatch(invariant, ("power_trace", "power_clock_provenance.file"), "power trace filename does not match record"))
    actual_file = report.get("file")
    if actual_file is not None and actual_file != trace_name:
        mismatches.append(_mismatch(invariant, ("power_trace",), "power trace path basename does not match record"))
    actual_hash = report.get("sha256")
    declared_hash = declared.get("sha256", _MISSING)
    if actual_hash is not None and declared_hash is not _MISSING and declared_hash is not None and declared_hash != actual_hash:
        mismatches.append(_mismatch(invariant, ("power_trace_sha256", "power_clock_provenance.sha256"), "power trace SHA-256 does not match actual bytes"))
    if ctx.power_trace_bytes is not None:
        supplied_hash = hashlib.sha256(ctx.power_trace_bytes).hexdigest()
        if declared_hash is _MISSING or declared_hash != supplied_hash:
            mismatches.append(_mismatch(invariant, ("power_trace_sha256",), "power trace SHA-256 does not match supplied bytes"))
    # Compatibility branch: a basename-only builder call has no bytes to
    # inspect, so unavailable physical facts are omitted from this check.  It
    # remains diagnostic-only; _timing_block_reason independently rejects any
    # positive timing claim from this branch.
    legacy_unverified = declared.get("aiclk_source") == "legacy_unverified"
    actual_available = report.get("actual_bytes_available") is True
    interval_extrema_policy = declared.get("interval_extrema_policy", _MISSING)
    if interval_extrema_policy is not _MISSING:
        if interval_extrema_policy != INTERVAL_EXTREMA_POLICY_POSITIVE_DURATION_LEFT_HELD:
            mismatches.append(
                _mismatch(
                    invariant,
                    (_POWER_CLOCK_PROVENANCE_INTERVAL_EXTREMA_POLICY_PATH,),
                    "power trace interval-extrema policy is not supported",
                )
            )
        elif actual_available and report.get("immutable_snapshot") is not True:
            mismatches.append(
                _mismatch(
                    invariant,
                    (_POWER_CLOCK_PROVENANCE_INTERVAL_EXTREMA_POLICY_PATH,),
                    "positive-duration interval-extrema policy was not applied to the trace",
                )
            )
    required_fields = (
        "columns",
        "sample_count",
        "csv_row_count",
        "valid_row_count",
        "in_run_valid_row_count",
        "first_timestamp",
        "last_timestamp",
        "run_start",
        "run_end",
        "coverage_complete",
        "coverage_definition",
        "aiclk_source",
    )
    if not actual_available and legacy_unverified:
        return mismatches
    if not actual_available:
        mismatches.append(_mismatch(invariant, ("power_trace",), "power trace actual bytes are unavailable for SHA-256 and row validation"))
        return mismatches
    mismatches.extend(_check_declared_trace_flags(record, report))
    if report.get("columns") != list(POWER_TRACE_COLUMNS):
        mismatches.append(_mismatch(invariant, ("power_trace.columns",), "power trace columns are not the declared telemetry columns"))
    for field in ("readable", "nonempty", "timestamps_parse", "timestamps_ordered"):
        if report.get(field) is not True:
            mismatches.append(_mismatch(invariant, (f"power_trace.{field}",), f"power trace {field} is not true"))
    if report.get("sample_count") != report.get("csv_row_count"):
        mismatches.append(_mismatch(invariant, ("power_trace.sample_count", "power_trace.csv_row_count"), "power trace sample_count does not equal CSV row count"))
    if report.get("valid_row_count") != report.get("csv_row_count"):
        mismatches.append(_mismatch(invariant, ("power_trace.valid_row_count", "power_trace.csv_row_count"), "power trace valid-row count does not equal CSV row count"))
    for field in required_fields:
        declared_value = declared.get(field, _MISSING)
        if declared_value is _MISSING or declared_value is None:
            mismatches.append(_mismatch(invariant, (f"power_clock_provenance.{field}",), f"power trace {field} is not declared"))
        elif declared_value != report.get(field):
            mismatches.append(_mismatch(invariant, (f"power_clock_provenance.{field}",), f"power trace {field} does not match actual trace"))
    for field in (
        "aiclk_selection",
        "aiclk_mhz_in_run_min",
        "aiclk_mhz_in_run_max",
        "aiclk_mhz_load_interval_weighted",
        "aiclk_mhz_load_interval_weighted_source",
        "aiclk_mhz_load_interval_weighted_seconds",
        "load_interval_start",
        "load_interval_end",
        "load_interval_source",
    ):
        declared_value = declared.get(field, _MISSING)
        if (
            declared_value is not _MISSING
            and declared_value is not None
            and declared_value != report.get(field)
        ):
            mismatches.append(
                _mismatch(
                    invariant,
                    (f"power_clock_provenance.{field}",),
                    f"power trace {field} does not match actual trace",
                )
            )
    if report.get("coverage_complete") is not True:
        mismatches.append(_mismatch(invariant, ("power_trace.coverage_complete",), "power trace coverage_complete is not true"))
    # Both nested and top-level fields are part of the record schema when
    # present; disagreement is never silently resolved by precedence.
    duplicate_fields = {
        "file": "power_trace",
        "sample_count": "power_trace_sample_count",
        "csv_row_count": "power_trace_csv_row_count",
        "valid_row_count": "power_trace_valid_row_count",
        "in_run_valid_row_count": "power_trace_in_run_valid_row_count",
        "sha256": "power_trace_sha256",
        "first_timestamp": "power_trace_coverage.first_timestamp",
        "last_timestamp": "power_trace_coverage.last_timestamp",
        "run_start": "run_start",
        "run_end": "run_end",
        "coverage_complete": "power_trace_coverage.coverage_complete",
        "interval_extrema_policy": "power_trace_interval_extrema_policy",
        "aiclk_mhz_in_run_min": "aiclk_mhz_in_run_min",
        "aiclk_mhz_in_run_max": "aiclk_mhz_in_run_max",
        "aiclk_source": "clock.aiclk_source",
        "aiclk_selection": _CLOCK_AICLK_SELECTION_PATH,
        "aiclk_mhz": "clock.aiclk_mhz",
    }
    nested = declared.get("nested", {})
    top = declared.get("top", {})
    for nested_name, top_name in duplicate_fields.items():
        nested_value = nested.get(nested_name, _MISSING)
        top_value = top.get(nested_name, _MISSING)
        if nested_name == "aiclk_source" and top_value is _MISSING:
            clock = _mapping(record, "clock")
            top_value = clock.get("aiclk_source", _MISSING) if clock else _MISSING
        if nested_name == "aiclk_mhz" and top_value is _MISSING:
            clock = _mapping(record, "clock")
            top_value = clock.get("aiclk_mhz", _MISSING) if clock else _MISSING
        if nested_name == "coverage_definition":
            try:
                if nested_value is not _MISSING:
                    nested_value = canonical_coverage_definition(nested_value)
                if top_value is not _MISSING:
                    top_value = canonical_coverage_definition(top_value)
            except (TypeError, ValueError):
                pass
        if nested_value is not _MISSING and top_value is not _MISSING and nested_value != top_value:
            label = "SHA-256" if nested_name == "sha256" else nested_name
            mismatches.append(_mismatch(invariant, (f"power_clock_provenance.{nested_name}", top_name), f"power provenance {label} does not match {top_name}"))
    return mismatches


def _timing_source_block_reason(source: Any) -> str | None:
    """Map an AICLK provenance sentinel to a diagnostic timing reason.

    The positive path is intentionally not represented by a truthy value: it
    is the single exact ``run_trace_samples`` sentinel.  Unknown, missing, and
    legacy values therefore remain blocked by the caller below.
    """
    if source == "legacy_unverified":
        return "legacy_power_trace_unverified"
    if source == "sampler_off_diagnostic":
        return "sampler_off_by_design"
    if source == "no_valid_in_run_samples":
        return "power_trace_no_valid_in_run_rows"
    if isinstance(source, str):
        lowered = source.lower()
        if source in TIMING_EVIDENCE_UNVERIFIED_AICLK_SOURCES or any(
            marker in lowered
            for marker in ("snapshot", "unverified", "unavailable", "legacy", "no_valid", "diagnostic")
        ):
            return "power_trace_aiclk_unverified"
    return None


def _timing_block_reason(
    record: Mapping[str, Any],
    ctx: ValidationContext,
    report: Mapping[str, Any] | None,
) -> str | None:
    """Return the first reason a record cannot claim timing evidence.

    This is deliberately stricter than the structural compatibility checks.  A
    report is usable only when the validator can inspect actual trace bytes,
    prove complete run coverage, and match the record's AICLK provenance to
    valid in-run samples.  The caller's timing flag is never evidence for any
    of those facts.
    """
    sampler = _sampler(record)
    mode = sampler.get("mode") if isinstance(sampler, Mapping) else None
    if mode == "off":
        return "sampler_off_by_design"
    if mode == "__mismatch__":
        return "sampler_metadata_unverified"
    if sampler is None and record.get("power_trace"):
        return "legacy_sampler_metadata_unverified"
    if isinstance(sampler, Mapping) and _check_sampler_contract(record, ctx):
        return "sampler_metadata_unverified"
    if _check_failure_check(record, ctx) or _check_cycle_budget(record, ctx):
        return "failure_metadata_unverified"
    if record.get("watcher") is True:
        return "watcher_diagnostic_only"
    if not record.get("power_trace"):
        return "power_trace_missing"

    declared = _declared_power_metadata(record)
    declared_source = declared.get("aiclk_source", _MISSING)
    source_reason = _timing_source_block_reason(declared_source)
    if source_reason == "legacy_power_trace_unverified" or declared_source in {
        "unverified",
        "unavailable",
    }:
        # These compatibility and sentinel branches are readable for old
        # callers, but they never prove trace bytes or in-run AICLK.
        return source_reason or "power_trace_aiclk_unverified"
    if report is None:
        return "power_trace_bytes_unavailable"
    if report.get("actual_bytes_available") is not True:
        return "power_trace_bytes_unavailable"
    if report.get("readable") is not True or report.get("nonempty") is not True:
        return "power_trace_unreadable"
    if report.get("sample_count") != report.get("csv_row_count"):
        return "power_trace_sample_count_mismatch"
    if report.get("valid_row_count") != report.get("csv_row_count"):
        return "power_trace_invalid_rows"
    if report.get("timestamps_parse") is not True:
        return "power_trace_timestamp_parse_failed"
    if report.get("timestamps_ordered") is not True:
        return "power_trace_timestamp_order_failed"
    if report.get("coverage_complete") is not True:
        return "power_trace_coverage_incomplete"
    coverage_definition = _declared_power_metadata(record).get(
        "coverage_definition", EXPLICIT_FINAL_SAMPLE
    )
    if report.get("covers_run_start") is not True:
        return "power_trace_coverage_incomplete"
    if coverage_definition == EXPLICIT_FINAL_SAMPLE and report.get("covers_run_end") is not True:
        return "power_trace_coverage_incomplete"
    if report.get("in_run_valid_row_count", 0) < 1 or report.get("aiclk_source") != "run_trace_samples":
        return "power_trace_no_valid_in_run_rows"

    clock = _mapping(record, "clock")
    clock_aiclk = clock.get("aiclk_mhz") if clock else None
    trace_aiclk = report.get("aiclk_mhz")
    if clock_aiclk != trace_aiclk:
        return "clock_aiclk_mismatch"
    if declared_source != "run_trace_samples":
        return source_reason or "power_trace_aiclk_not_in_run"

    # These checks are normally reported by their catalog entries.  Repeating
    # the physical and duplicate metadata gates here ensures that a caller
    # cannot retain a positive flag merely because a compatibility branch
    # skipped a structural fact.
    if _check_power_trace_facts(record, ctx):
        return "power_trace_metadata_unverified"
    if _check_trace_metadata_duplicates(record, ctx):
        return "power_trace_metadata_unverified"
    if _failure_flag(record):
        return "run_error_not_timing_evidence"
    params = _mapping(record, "parameters")
    ring = _mapping(record, "ring")
    if params is None or ring is None:
        return "run_counters_unverified"
    if params.get("dropped_frame_count") != 0 or ring.get("consumed_frame_count") != params.get("produced_frame_count"):
        return "run_incomplete_or_dropped_frames"
    if params.get("attempted_frame_count") != params.get("frame_count"):
        return "run_incomplete_or_dropped_frames"
    if _check_clock_source_evidence(record, ctx):
        return "clock_source_unaudited"
    source_evidence = _mapping(record, "clock_source_evidence")
    if source_evidence is None or source_evidence.get("audit_status") != "audited":
        return "clock_source_unaudited"
    return None


def _check_clock_and_timing(record: Mapping[str, Any], ctx: ValidationContext) -> list[dict[str, Any]]:
    invariant = "clock.timing_evidence"
    timing = record.get("timing_evidence", _MISSING)
    sampler = _sampler(record)
    mode = sampler.get("mode") if isinstance(sampler, Mapping) else None
    report = _trace_report(record, ctx)
    declared = _declared_power_metadata(record)
    mismatches: list[dict[str, Any]] = []
    timing_kind = _timing_record_kind(record)
    if timing_kind in {RECORD_KIND_ERROR, RECORD_KIND_REJECTED}:
        expected_reason = (
            TIMING_EVIDENCE_ERROR_RECORD_REASON
            if timing_kind == RECORD_KIND_ERROR
            else TIMING_EVIDENCE_REJECTED_RECORD_REASON
        )
        if timing is not False:
            mismatches.append(
                _mismatch(
                    invariant,
                    ("timing_evidence",),
                    f"{timing_kind} records must have timing_evidence=false",
                )
            )
        provenance = record.get("power_clock_provenance")
        if isinstance(provenance, Mapping) and provenance.get("timing_evidence") is not False:
            mismatches.append(
                _mismatch(
                    invariant,
                    ("power_clock_provenance.timing_evidence",),
                    f"{timing_kind} records must have power provenance timing_evidence=false",
                )
            )
        reason = record.get("timing_evidence_reason")
        if reason != expected_reason:
            mismatches.append(
                _mismatch(
                    invariant,
                    ("timing_evidence_reason",),
                    f"{timing_kind} records require timing_evidence_reason={expected_reason!r}",
                )
            )
        provenance_reason = (
            provenance.get("timing_evidence_reason")
            if isinstance(provenance, Mapping)
            else None
        )
        if provenance_reason != expected_reason:
            mismatches.append(
                _mismatch(
                    invariant,
                    ("power_clock_provenance.timing_evidence_reason",),
                    f"{timing_kind} records require power provenance reason={expected_reason!r}",
                )
            )
        return mismatches
    clock = _mapping(record, "clock")
    clock_aiclk = clock.get("aiclk_mhz") if clock else _MISSING
    if clock is not None and not _is_int(clock_aiclk, positive=True):
        mismatches.append(_mismatch(invariant, ("clock.aiclk_mhz",), "clock.aiclk_mhz must be a positive integer"))
    declared_aiclk = declared.get("aiclk_mhz", _MISSING)
    if declared_aiclk is not _MISSING and declared_aiclk is not None and _is_int(clock_aiclk, positive=True) and declared_aiclk != clock_aiclk:
        mismatches.append(_mismatch(invariant, ("clock.aiclk_mhz", "power_clock_provenance.aiclk_mhz"), "power provenance AICLK does not match clock.aiclk_mhz"))
    if report is not None and report.get("aiclk_mhz") is not None and _is_int(clock_aiclk, positive=True) and clock_aiclk != report.get("aiclk_mhz"):
        mismatches.append(_mismatch(invariant, ("clock.aiclk_mhz", "power_trace.aiclk_mhz"), "clock.aiclk_mhz does not equal in-run power-trace AICLK"))
    if timing is _MISSING:
        return mismatches
    if not isinstance(timing, bool):
        mismatches.append(_mismatch(invariant, ("timing_evidence",), "timing_evidence must be a boolean"))
        return mismatches
    reason = record.get("timing_evidence_reason")
    provenance = record.get("power_clock_provenance")
    if isinstance(provenance, Mapping):
        if "timing_evidence" in provenance and provenance.get("timing_evidence") != timing:
            mismatches.append(_mismatch(invariant, ("timing_evidence", "power_clock_provenance.timing_evidence"), "power provenance timing_evidence does not match record"))
        if "timing_evidence_reason" in provenance and isinstance(reason, str) and provenance.get("timing_evidence_reason") != reason:
            mismatches.append(_mismatch(invariant, ("timing_evidence_reason", "power_clock_provenance.timing_evidence_reason"), "power provenance timing_evidence_reason does not match record"))
    if timing:
        block = _timing_block_reason(record, ctx, report)
        if block is not None:
            mismatches.append(_mismatch(invariant, ("timing_evidence", "timing_evidence_reason"), f"timing_evidence=true is not permitted: {block}"))
        if declared.get("aiclk_source") != "run_trace_samples":
            # Structural compatibility never widens the positive timing
            # contract: legacy and unknown provenance are all non-timing.
            mismatches.append(_mismatch(invariant, ("clock.aiclk_source", "power_clock_provenance.aiclk_source"), "timing AICLK is not sourced from valid in-run trace samples"))
    else:
        if mode in {"default", "explicit"} and (not isinstance(reason, str) or not reason.strip()):
            mismatches.append(_mismatch(invariant, ("timing_evidence", "timing_evidence_reason"), "sampled records with timing_evidence=false require a non-timing reason"))
        if mode == "off" and not isinstance(reason, str):
            absent_reason = record.get("power_trace_absent_reason")
            if absent_reason != "sampler_off_by_design":
                mismatches.append(_mismatch(invariant, ("timing_evidence_reason", "power_trace_absent_reason"), "sampler-off timing evidence requires sampler_off_by_design"))
        if isinstance(reason, str) and reason in {"power_trace_run_samples", "timing"} and mode != "off":
            mismatches.append(_mismatch(invariant, ("timing_evidence_reason",), "timing_evidence=false requires a non-timing reason"))
    return mismatches


def _check_trace_metadata_duplicates(record: Mapping[str, Any], ctx: ValidationContext) -> list[dict[str, Any]]:
    # Keep this as a catalog entry so the nested/top-level relationship is not
    # hidden inside the timing policy.  The physical fact checks are separate.
    del ctx
    invariant = "power_trace.metadata_duplicates"
    declared = _declared_power_metadata(record)
    nested = declared.get("nested", {})
    top = declared.get("top", {})
    mismatches: list[dict[str, Any]] = []
    for nested_name, top_name in {
        "file": "power_trace",
        "sample_count": "power_trace_sample_count",
        "csv_row_count": "power_trace_csv_row_count",
        "valid_row_count": "power_trace_valid_row_count",
        "in_run_valid_row_count": "power_trace_in_run_valid_row_count",
        "sha256": "power_trace_sha256",
        "coverage_definition": _POWER_TRACE_COVERAGE_DEFINITION_PATH,
        "interval_extrema_policy": "power_trace_interval_extrema_policy",
        "aiclk_mhz_in_run_min": "aiclk_mhz_in_run_min",
        "aiclk_mhz_in_run_max": "aiclk_mhz_in_run_max",
    }.items():
        left = nested.get(nested_name, _MISSING)
        right = top.get(nested_name, _MISSING)
        if left is not _MISSING and right is not _MISSING and left is not None and right is not None and left != right:
            label = "SHA-256" if nested_name == "sha256" else nested_name
            mismatches.append(_mismatch(invariant, (f"power_clock_provenance.{nested_name}", top_name), f"power provenance {label} does not match {top_name}"))
    return mismatches



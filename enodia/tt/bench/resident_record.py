"""Shared Issue #104 resident-record catalog, pair analysis, and validator.

This module is the single authority for the relationships in a resident
measurement record.  The builder in :mod:`resident_harness` and the board-free
analyzer both call :func:`validate_resident_record`; neither caller owns a
second copy of these checks.  The validator guarantees required field
presence, declared field type/range, and major relationships.  Telemetry and
other production fields that are not yet declared are retained and reported as
warnings rather than rejected; full record-kind and coverage-flag consistency
is deferred to Issue #110.

The outlier builder is the single constructor for the pair and sampler
catalog.  The resident runner and board-free analyzer both call
:func:`build_outlier_analysis`; neither caller reconstructs a partial object.
The catalog is intentionally executable.  ``RESIDENT_INVARIANT_CATALOG`` is a
table of ``ResidentInvariant`` entries, and the validator iterates that table
rather than selecting ad-hoc checks in either caller.  The relationships in
the catalog are:

* ``parameters.frame_count`` is the configured attempt count.  Normal runs
  satisfy ``attempted = produced + dropped`` and ``aborted_attempts = 0``;
  error runs satisfy ``attempted = produced + dropped + aborted_attempts`` with
  at most one aborted attempt.  Produced, consumed, dropped, and aborted are
  non-negative and consumed cannot exceed produced.
* ``raw_timestamps.count`` equals the supplied timestamp sequence count when
  available.  The interval count is ``raw_count - 1`` and therefore equals
  ``histogram.N``; histogram bin counts sum to ``N``.  Timestamp count and
  SHA-256 also agree with supplied raw-byte metadata.
* The ring repeats the attempted/produced/consumed/dropped counts, records
  ``producer_full_count = dropped`` and ``overflow_count = producer_full_count``,
  and has occupancy ``produced - consumed`` in ``[0, ring_pages]``.
* ``outlier_analysis`` is generated by :func:`build_outlier_analysis`.  Its
  pair count agrees with starts, pair objects, pair sums, endpoints, event
  arrays, and adjacent start gaps.  Pair object values, sums, order, elapsed
  positions, aggregate sums, gap counts, and duplicate-aware raw
  correspondence are checked whenever the timestamp stream is available.
* A sampled trace's declared filename, columns, byte hash, CSV/sample/valid
  row counts, first/last timestamps, run bounds, in-run AICLK, and PR #109
  ``coverage_complete`` value agree with the actual CSV when bytes are
  supplied.  Sampler-off is absent by design and is diagnostic-only.
* ``telemetry_sampler`` follows the shared ``SAMPLER_CONTRACT``: off has no
  interval, default is exactly 2.0 seconds, and explicit is positive and
  finite.  Top-level and environment copies must agree.
* ``clock.aiclk_mhz`` must equal the AICLK from valid in-run trace samples
  whenever timing evidence is true.  Timing evidence is never accepted for
  sampler-off, Watcher, snapshot-only or otherwise unverified AICLK, missing
  bytes, basename-only compatibility input, invalid or incomplete traces, a
  clock mismatch, or any corresponding provenance mismatch.  A builder call
  may force the claim false and retain a machine-readable reason; an analyzer
  call reports the mismatch without mutating its input.  Validation is scoped
  to records carrying the current runner marker; records without that marker
  are classified as out_of_scope rather than being treated as invalid.  The
  historical analyzer may use a persisted record clock as explicitly
  unverified elapsed-time provenance, but it never turns that into timing
  evidence.

Compatibility skips are deliberately narrow and are listed in
``TIMING_EVIDENCE_COMPATIBILITY_BRANCHES``: a basename-only legacy trace may
omit unavailable byte facts; a sampler-off record may omit trace facts by
design; and a record predating the timing field may omit that field.  Each
skip is followed by the timing
check, and every positive claim still requires the exact ``run_trace_samples``
provenance sentinel plus readable, complete trace bytes.  The unverified
catalog includes legacy and basename-only values, ``unverified`` and
``unavailable`` sentinels, snapshot/pre-run snapshot values,
``sampler_off_diagnostic``, and ``no_valid_in_run_samples``; trace failures
are separately reasoned as missing, unreadable, empty, invalid, or incomplete.

The validator returns a JSON-serializable report with one structured check per
catalog entry.  ``builder=True`` additionally applies the safe timing policy
and raises for hard contradictions when ``raise_on_error`` is true.  Physical
trace availability failures are retained in the report so a builder can write
a diagnostic record, while numeric/schema contradictions remain strict.
"""

